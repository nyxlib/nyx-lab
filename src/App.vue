<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {inject, reactive, computed, onMounted} from 'vue';

import {useNyxStore} from 'vue-nyx';

/*--------------------------------------------------------------------------------------------------------------------*/

import useConfigStore from '@/stores/config';

import getRuntime from '@/runtime';

/*--------------------------------------------------------------------------------------------------------------------*/

import icons from '@/assets/icons.json';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const dialog = inject('dialog');

/*--------------------------------------------------------------------------------------------------------------------*/

const configStore = useConfigStore();

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const runtime = getRuntime();

/*--------------------------------------------------------------------------------------------------------------------*/
/* COMPUTED                                                                                                           */
/*--------------------------------------------------------------------------------------------------------------------*/

const menuEntries = computed(() => [

    /*----------------------------------------------------------------------------------------------------------------*/

    ...Object.values(configStore.appPanels).flatMap((appPanel) => appPanel.panels.map((panel, idx) => ({
        id: `panel_${appPanel.descr.id}_${idx}`,
        rank: appPanel.descr.rank,
        path: panel.path,
        title: panel.title,
        logo: panel.logo,
    }))),

    /*----------------------------------------------------------------------------------------------------------------*/

    ...Object.values(configStore.globals.addons).filter((addon) => addon.type === 'page' && (addon.url.startsWith('http://') || addon.url.startsWith('https://')) && addon.enabled).map((addon) => ({
        key: `page_${addon.id}`,
        rank: addon.rank,
        path: `/external/${addon.id}`,
        title: addon.title,
        logo: icons[addon.icon || 'bi-question'],
    })),

    /*----------------------------------------------------------------------------------------------------------------*/

].sort((x, y) => x.rank - y.rank));

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const about = () => {

    dialog.show([
        '<h1>Nyx Lab</h1>',
        '<br />',
        'Website: <a href="https://nyxlib.org/" target="_blank">https://nyxlib.org/</a>',
        '<br /><br />',
        'Repository: <a href="https://github.com/nyxlib/nyx-lab/" target="_blank">https://github.com/nyxlib/nyx-lab/</a>',
        '<br /><br />',
        'Author: Jérôme ODIER &lt;<a href="mailto:jerome.odier@lpsc.in2p3.fr">jerome.odier@lpsc.in2p3.fr</a>&gt;',
    ].join('\n'), 'About', {icon: 'info', html: true});
};

/*--------------------------------------------------------------------------------------------------------------------*/

const onUpdateWindow = () => {

    runtime.isMaximized().then((maximized) => {

        if(maximized) {
            document.body.dataset.maximized = 'true';
        } else {
            document.body.dataset.maximized = 'false';
        }
    });
};

/*--------------------------------------------------------------------------------------------------------------------*/

const onCloseRequested = () => {

    if(configStore.modified)
    {
        return dialog.confirm('Are you sure you want to close?', 'Nyx Lab').then((choice) => {

            if(choice)
            {
                runtime.destroy();
            }
        });
    }
    else
    {
        runtime.destroy();
    }
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    runtime.onOpenConfigRequested((text) => {

        configStore._setConfig(JSON.parse(text), true);
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    runtime.onCloseRequested(onCloseRequested);

    /*----------------------------------------------------------------------------------------------------------------*/

    if(runtime.isBrowser)
    {
        document.body.dataset.environment = 'browser';
    }
    else if(runtime.isMobile)
    {
        document.body.dataset.environment = 'mobile';
    }
    else if(runtime.isDesktop)
    {
        document.body.dataset.environment = 'desktop';

        /*------------------------------------------------------------------------------------------------------------*/

        window.addEventListener('resize', () => {

            onUpdateWindow();
        });

        onUpdateWindow();

        /*------------------------------------------------------------------------------------------------------------*/

        document.querySelector('[data-tauri-drag-region]').addEventListener('dblclick', (e) => {

            if(e.target.tagName.toLowerCase() === 'div')
            {
                runtime.toggleMaximize();
            }
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    configStore.init();

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

