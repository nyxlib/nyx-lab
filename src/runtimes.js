/* TAURI RUNTIME                                                                                                      */
/*--------------------------------------------------------------------------------------------------------------------*/

const _buildTauriRuntime = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const appWindow = getCurrentWindow();

    /*----------------------------------------------------------------------------------------------------------------*/

    return {

        /*------------------------------------------------------------------------------------------------------------*/
        /* ENVIRONMENT                                                                                                */
        /*------------------------------------------------------------------------------------------------------------*/

        isBrowser: false,
        isDesktop: !IS_MOBILE,
        isMobile: IS_MOBILE,

        /*------------------------------------------------------------------------------------------------------------*/
        /* DESKTOP                                                                                                    */
        /*------------------------------------------------------------------------------------------------------------*/

        minimize: () => appWindow.minimize(),

        /*------------------------------------------------------------------------------------------------------------*/

        maximize: () => appWindow.maximize(),

        /*------------------------------------------------------------------------------------------------------------*/

        toggleMaximize: () => appWindow.toggleMaximize(),

        /*------------------------------------------------------------------------------------------------------------*/

        isMaximized: () => appWindow.isMaximized(),

        /*------------------------------------------------------------------------------------------------------------*/

        close: () => appWindow.close(),

        /*------------------------------------------------------------------------------------------------------------*/

        destroy: () => appWindow.destroy(),

        /*------------------------------------------------------------------------------------------------------------*/

        onCloseRequested: (callback) => {

            /*--------------------------------------------------------------------------------------------------------*/

            let unlisten = null;

            /*--------------------------------------------------------------------------------------------------------*/

            Window.getByLabel('main').then((mainWindow) => {

                return mainWindow.listen('tauri://close-requested', callback);

            }).then((fn) => {

                unlisten = fn;
            });

            /*--------------------------------------------------------------------------------------------------------*/

            return () => {

                if(unlisten)
                {
                    unlisten();
                }
            };

            /*--------------------------------------------------------------------------------------------------------*/
        },

        /*------------------------------------------------------------------------------------------------------------*/

        onOpenConfigRequested: () => () => {},

        /*------------------------------------------------------------------------------------------------------------*/
        /* NOTIFICATION                                                                                               */
        /*------------------------------------------------------------------------------------------------------------*/

        notifyIsPermissionGranted: () => notification.isPermissionGranted(),

        /*------------------------------------------------------------------------------------------------------------*/

        notifyRequestPermission: () => notification.requestPermission(),

        /*------------------------------------------------------------------------------------------------------------*/

        notifySend: (title, body) => notification.sendNotification({
            title: title,
            body: body,
        }),

        /*------------------------------------------------------------------------------------------------------------*/
        /* DIALOG                                                                                                     */
        /*------------------------------------------------------------------------------------------------------------*/

        message: (message, options = {}) => dialog.message(message, options),

        /*------------------------------------------------------------------------------------------------------------*/

        confirm: (message, options = {}) => dialog.confirm(message, options),

        /*------------------------------------------------------------------------------------------------------------*/

        open: (defaultPath, _typeMime, typeName, typeExts) => {

            return dialog.open({
                multiple: false,
                defaultPath: defaultPath,
                filters: [{
                    name: typeName,
                    extensions: typeExts,
                }]
            }).then((filename) => {

                if(filename)
                {
                    return fs.readTextFile(filename).then((text) => {

                        return [text, filename];

                    });
                }

                throw new Error('Operation cancelled');
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/

        save: (defaultPath, _typeMime, typeName, typeExts, contents) => {

            return dialog.save({
                defaultPath: defaultPath,
                filters: [{
                    name: typeName,
                    extensions: typeExts,
                }]
            }).then((filename) => {

                if(filename)
                {
                    return fs.writeTextFile(filename, contents).then(() => {

                        return filename;

                    });
                }

                throw new Error('Operation cancelled');
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/
        /* GEOLOCATION                                                                                                */
        /*------------------------------------------------------------------------------------------------------------*/

        checkGeolocationPermissions: () => geolocation.checkPermissions(),

        /*------------------------------------------------------------------------------------------------------------*/

        requestGeolocationPermissions: (permissions) => geolocation.requestPermissions(permissions),

        /*------------------------------------------------------------------------------------------------------------*/

        getCurrentPosition: (options) => geolocation.getCurrentPosition(options),

        /*------------------------------------------------------------------------------------------------------------*/
        /* ADDON CACHE                                                                                                */
        /*------------------------------------------------------------------------------------------------------------*/

        /*------------------------------------------------------------------------------------------------------------*/
        /* ADDON CACHE                                                                                                */
        /*------------------------------------------------------------------------------------------------------------*/

        deleteCachedFile: (pathname) => {

            return import('@tauri-apps/plugin-store').then(({load}) => {

                return load('nyx-addons-store.json').then((store) => {

                    return store.delete(pathname);
                });
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/

        deleteCachedFiles: () => {

            return import('@tauri-apps/plugin-store').then(({load}) => {

                return load('nyx-addons-store.json').then((store) => {

                    return store.clear();
                });
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/

        listCachedFiles: () => {

            return import('@tauri-apps/plugin-store').then(({load}) => {

                return load('nyx-addons-store.json').then((store) => {

                    return store.keys().then((keys) => {

                        return keys.map((key) => ({
                            path: key,
                            size: 0x0,
                        }));
                    });
                });
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/
    };

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* EXPORTS                                                                                                            */
/*--------------------------------------------------------------------------------------------------------------------*/

export const getRuntime = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(_runtime !== null)
    {
        return _runtime;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    /**/ if(HAS_TAURI) {
        _runtime = _buildTauriRuntime();
    }
    else if(HAS_ELECTRON) {
        _runtime = _buildElectronRuntime();
    }
    else {
        _runtime = _buildBrowserRuntime();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    return _runtime;

    /*----------------------------------------------------------------------------------------------------------------*/
};

