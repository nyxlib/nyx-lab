/* TAURI RUNTIME                                                                                                      */
/*--------------------------------------------------------------------------------------------------------------------*/

const _buildTauriRuntime = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const isMobile = ['android', 'ios'].includes(os.type());

    const window = getCurrentWindow();

    /*----------------------------------------------------------------------------------------------------------------*/

    return {

        /*------------------------------------------------------------------------------------------------------------*/
        /* ENVIRONMENT                                                                                                */
        /*------------------------------------------------------------------------------------------------------------*/

        isBrowser: false,
        isDesktop: !isMobile,
        isMobile: isMobile,

        /*------------------------------------------------------------------------------------------------------------*/
        /* DESKTOP                                                                                                    */
        /*------------------------------------------------------------------------------------------------------------*/

        minimize: () => window.minimize(),

        /*------------------------------------------------------------------------------------------------------------*/

        maximize: () => window.maximize(),

        /*------------------------------------------------------------------------------------------------------------*/

        toggleMaximize: () => window.toggleMaximize(),

        /*------------------------------------------------------------------------------------------------------------*/

        isMaximized: () => window.isMaximized(),

        /*------------------------------------------------------------------------------------------------------------*/

        close: () => window.close(),

        /*------------------------------------------------------------------------------------------------------------*/

        destroy: () => window.destroy(),

        /*------------------------------------------------------------------------------------------------------------*/

        onCloseRequested: (callback) => {

            /*--------------------------------------------------------------------------------------------------------*/

            let unlisten = null;

            /*--------------------------------------------------------------------------------------------------------*/

            Window.getByLabel('main').then((mainWindow) => {

                return mainWindow.listen('tauri://close-requested', callback);

            }).then((fn) => {

                unlisten = fn;
            });

            /*--------------------------------------------------------------------------------------------------------*/

            return () => {

                if(unlisten)
                {
                    unlisten();
                }
            };

            /*--------------------------------------------------------------------------------------------------------*/
        },

        /*------------------------------------------------------------------------------------------------------------*/

        onOpenConfigRequested: () => () => {},

        /*------------------------------------------------------------------------------------------------------------*/
        /* NOTIFICATION                                                                                               */
        /*------------------------------------------------------------------------------------------------------------*/

        notifyIsPermissionGranted: () => notification.isPermissionGranted(),

        /*------------------------------------------------------------------------------------------------------------*/

        notifyRequestPermission: () => notification.requestPermission(),

        /*------------------------------------------------------------------------------------------------------------*/

        notifySend: (title, body) => notification.sendNotification({
            title: title,
            body: body,
        }),

        /*------------------------------------------------------------------------------------------------------------*/
        /* DIALOG                                                                                                     */
        /*------------------------------------------------------------------------------------------------------------*/

        message: (message, options = {}) => dialog.message(message, options),

        /*------------------------------------------------------------------------------------------------------------*/

        confirm: (message, options = {}) => dialog.confirm(message, options),

        /*------------------------------------------------------------------------------------------------------------*/

        open: (defaultPath, _typeMime, typeName, typeExts) => {

            return dialog.open({
                defaultPath: defaultPath,
                filters: [{
                    name: typeName,
                    extensions: typeExts,
                }],
                /**/ multiple /**/: false,
            }).then((name) => {

                if(name)
                {
                    return fs.readTextFile(name).then((text) => {

                        return {text: text, name: name};
                    });
                }

                return null;
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/

        save: (defaultPath, _typeMime, typeName, typeExts, text) => {

            return dialog.save({
                defaultPath: defaultPath,
                filters: [{
                    name: typeName,
                    extensions: typeExts,
                }],
                canCreateDirectories: true,
            }).then((name) => {

                if(name)
                {
                    return fs.writeTextFile(name, text).then(() => {

                        return {text: text, name: name};
                    });
                }

                return null;
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/
        /* BROWSER                                                                                                    */
        /*------------------------------------------------------------------------------------------------------------*/

        browse: (url) => shell.open(url),

        /*------------------------------------------------------------------------------------------------------------*/
        /* GEOLOCATION                                                                                                */
        /*------------------------------------------------------------------------------------------------------------*/

        geolocCheckPermissions: () => geolocation.checkPermissions(),

        /*------------------------------------------------------------------------------------------------------------*/

        geolocRequestPermission: (permissions) => geolocation.requestPermissions(permissions),

        /*------------------------------------------------------------------------------------------------------------*/

        getCurrentPosition: (options) => geolocation.getCurrentPosition(options),

        /*------------------------------------------------------------------------------------------------------------*/
        /* ADDON CACHE                                                                                                */
        /*------------------------------------------------------------------------------------------------------------*/

        deleteCachedFile: (pathname) => {

            return import('@tauri-apps/plugin-store').then(({load}) => {

                return load('nyx-addons-store.json').then((store) => {

                    return store.delete(pathname);
                });
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/

        deleteCachedFiles: () => {

            return import('@tauri-apps/plugin-store').then(({load}) => {

                return load('nyx-addons-store.json').then((store) => {

                    return store.clear();
                });
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/

        listCachedFiles: () => {

            return import('@tauri-apps/plugin-store').then(({load}) => {

                return load('nyx-addons-store.json').then((store) => {

                    return store.keys().then((keys) => {

                        return keys.map((key) => ({
                            path: key,
                            size: 0x0,
                        }));
                    });
                });
            });
        },

        /*------------------------------------------------------------------------------------------------------------*/
    };

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* EXPORTS                                                                                                            */
/*--------------------------------------------------------------------------------------------------------------------*/

const getRuntime = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(_runtime === null)
    {
        /**/ if(HAS_ELECTRON) {
            _runtime = _buildElectronRuntime();
        }
        else if(HAS_TAURI) {
           _runtime = _buildTauriRuntime();
        }
        else {
            _runtime = _buildBrowserRuntime();
        }
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    return _runtime;
};

/*--------------------------------------------------------------------------------------------------------------------*/

export default getRuntime;

