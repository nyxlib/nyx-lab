/*--------------------------------------------------------------------------------------------------------------------*/

import {Window, getCurrentWindow} from '@tauri-apps/api/window';

import * as fs from '@tauri-apps/plugin-fs';
import * as dialog from '@tauri-apps/plugin-dialog';
import * as geolocation from '@tauri-apps/plugin-geolocation';
import * as notification from '@tauri-apps/plugin-notification';

/*--------------------------------------------------------------------------------------------------------------------*/

let _runtime = null;

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const HAS_TAURI = window['__TAURI__'] !== undefined;

const HAS_ELECTRON = window['__ELECTRON__'] !== undefined;

const IS_MOBILE = ['android', 'ios'].includes(window['__NYX_OS_TYPE__']);

/*--------------------------------------------------------------------------------------------------------------------*/
/* BROWSER RUNTIME                                                                                                    */
/*--------------------------------------------------------------------------------------------------------------------*/

const _buildBrowserRuntime = () => ({

    /*----------------------------------------------------------------------------------------------------------------*/
    /* ENVIRONMENT                                                                                                    */
    /*----------------------------------------------------------------------------------------------------------------*/

    isBrowser: true,
    isDesktop: false,
    isMobile: false,

    /*----------------------------------------------------------------------------------------------------------------*/
    /* DESKTOP                                                                                                        */
    /*----------------------------------------------------------------------------------------------------------------*/

    minimize: () => Promise.reject(new Error('Not supported.')),

    /*----------------------------------------------------------------------------------------------------------------*/

    maximize: () => Promise.reject(new Error('Not supported.')),

    /*----------------------------------------------------------------------------------------------------------------*/

    toggleMaximize: () => Promise.reject(new Error('Not supported.')),

    /*----------------------------------------------------------------------------------------------------------------*/

    isMaximized: () => Promise.reject(new Error('Not supported.')),

    /*----------------------------------------------------------------------------------------------------------------*/

    close: () => Promise.reject(new Error('Not supported.')),

    /*----------------------------------------------------------------------------------------------------------------*/

    destroy: () => Promise.reject(new Error('Not supported.')),

    /*----------------------------------------------------------------------------------------------------------------*/

    onCloseRequested: () => () => {},

    /*----------------------------------------------------------------------------------------------------------------*/

    onOpenConfigRequested: () => () => {},

    /*----------------------------------------------------------------------------------------------------------------*/
    /* NOTIFICATION                                                                                                   */
    /*----------------------------------------------------------------------------------------------------------------*/

    notifyIsPermissionGranted: () => Promise.resolve(Notification.permission === 'granted'),

    /*----------------------------------------------------------------------------------------------------------------*/

    notifyRequestPermission: () => Notification.requestPermission(),

    /*----------------------------------------------------------------------------------------------------------------*/

    notifySend: (title, body) => {

        new Notification(title, {
            body: body
        });
    },

    /*----------------------------------------------------------------------------------------------------------------*/
    /* DIALOG                                                                                                         */
    /*----------------------------------------------------------------------------------------------------------------*/

    message: (message, _options = {}) => {

        alert(message);

        return Promise.resolve();
    },

    /*----------------------------------------------------------------------------------------------------------------*/

    confirm: (message, _options = {}) => {

        return Promise.resolve(confirm(message));
    },

    /*----------------------------------------------------------------------------------------------------------------*/

    open: (defaultPath, typeMime, typeName, typeExts) => new Promise((resolve, reject) => {

        /*------------------------------------------------------------------------------------------------------------*/

        const el = document.createElement('input');

        el.type = /*-------*/ 'file' /*-------*/;

        el.accept = typeExts.map((x) => `.${x}`)
            .join(',')
        ;

        /*------------------------------------------------------------------------------------------------------------*/

        el.addEventListener('change', () => {

            /*--------------------------------------------------------------------------------------------------------*/

            const file = el.files?.[0];

            if(file)
            {
                file.text().then((text) => {

                    resolve([text, null]);

                }, reject);
            }
            else
            {
                reject(new Error('Operation cancelled'));
            }

            /*--------------------------------------------------------------------------------------------------------*/

            el.remove();

            /*--------------------------------------------------------------------------------------------------------*/

        }, {
            once: true
        });

        /*------------------------------------------------------------------------------------------------------------*/

        document.body.appendChild(el);

        /*------------------------------------------------------------------------------------------------------------*/

        el.click();

        /*------------------------------------------------------------------------------------------------------------*/
    }),

    /*----------------------------------------------------------------------------------------------------------------*/

    save: (defaultPath, typeMime, _typeName, _typeExts, contents) => {

        /*------------------------------------------------------------------------------------------------------------*/

        const blob = new Blob([contents], {type: typeMime});

        const el = document.createElement('a');

        /*------------------------------------------------------------------------------------------------------------*/

        el.href = URL.createObjectURL(blob);
        el.download = defaultPath;
        el.style.display = 'none';

        /*------------------------------------------------------------------------------------------------------------*/

        document.body.appendChild(el);  /* NOSONAR */
        el.click();
        document.body.removeChild(el);  /* NOSONAR */

        /*------------------------------------------------------------------------------------------------------------*/

        return Promise.resolve(null);

        /*------------------------------------------------------------------------------------------------------------*/
    },

    /*----------------------------------------------------------------------------------------------------------------*/
    /* GEOLOCATION                                                                                                    */
    /*----------------------------------------------------------------------------------------------------------------*/

    checkGeolocationPermissions: () => Promise.resolve({
        location: 'prompt'
    }),

    /*----------------------------------------------------------------------------------------------------------------*/

    requestGeolocationPermissions: () => Promise.resolve({
        location: 'granted'
    }),

    /*----------------------------------------------------------------------------------------------------------------*/

    getCurrentPosition: (options) => new Promise((resolve, reject) => {

        /*------------------------------------------------------------------------------------------------------------*/

        if(typeof navigator.geolocation !== 'object')
        {
            reject(new Error('Not supported.'));

            return;
        }

        /*------------------------------------------------------------------------------------------------------------*/

        navigator.geolocation.getCurrentPosition(resolve, reject, options);

        /*------------------------------------------------------------------------------------------------------------*/
    }),

    /*----------------------------------------------------------------------------------------------------------------*/
    /* ADDON CACHE                                                                                                    */
    /*----------------------------------------------------------------------------------------------------------------*/

    deleteCachedFile: () => Promise.reject(new Error('Not supported.')),

    /*----------------------------------------------------------------------------------------------------------------*/

    deleteCachedFiles: () => Promise.reject(new Error('Not supported.')),

    /*----------------------------------------------------------------------------------------------------------------*/

    listCachedFiles: () => Promise.resolve([]),

    /*----------------------------------------------------------------------------------------------------------------*/
});

