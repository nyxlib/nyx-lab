<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, watch, onMounted, onBeforeUnmount} from 'vue';

import Plotly from 'plotly.js-dist-min';

import {useNyxStore} from 'vue-nyx';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    variables1: {
        type: Array,
        required: true,
    },
    variables2: {
        type: Array,
        required: true,
    },
    variables3: {
        type: Array,
        required: true,
    },
    title1: {
        type: String,
        default: null,
    },
    title2: {
        type: String,
        default: null,
    },
    title3: {
        type: String,
        default: null,
    },
    enabled: {
        type: Object,
        required: true,
    },
    maxPoints: {
        type: Number,
        required: true,
    },
    options: {
        type: Object,
        required: true,
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const plotEl = ref(null);

/*--------------------------------------------------------------------------------------------------------------------*/

let resizeObserver = null;

/*--------------------------------------------------------------------------------------------------------------------*/

const stops = [];

/*--------------------------------------------------------------------------------------------------------------------*/

const lastVals1 = new Map();
const lastVals2 = new Map();
const lastVals3 = new Map();

/*--------------------------------------------------------------------------------------------------------------------*/

const FRAME_TRACE_COUNT = 12;

/*--------------------------------------------------------------------------------------------------------------------*/

let lastCamera = null;

/*--------------------------------------------------------------------------------------------------------------------*/

let lastRangesKey = null;

/*--------------------------------------------------------------------------------------------------------------------*/

let cachedRanges = {
    xRange: [-1, 1],
    yRange: [-1, 1],
    zRange: [-1, 1],
};

/*--------------------------------------------------------------------------------------------------------------------*/

let cachedFrameXYZ = null;

/*--------------------------------------------------------------------------------------------------------------------*/

const enabledByIndex = [];

/*--------------------------------------------------------------------------------------------------------------------*/

let flushScheduled = false;

const pendingX = [];
const pendingY = [];
const pendingZ = [];

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const getN = () => Math.min(props.variables1.length, props.variables2.length, props.variables3.length);

/*--------------------------------------------------------------------------------------------------------------------*/

const stopWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const stop of stops)
    {
        stop();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stops.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const toFiniteNumber = (v) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const x = (typeof v === 'string') ? Number(v) : v;

    /*----------------------------------------------------------------------------------------------------------------*/

    return Number.isFinite(x) ? x : undefined;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const getRange = (minKey, maxKey, fallbackMin, fallbackMax) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const min = toFiniteNumber(props.options[minKey]);
    const max = toFiniteNumber(props.options[maxKey]);

    /*----------------------------------------------------------------------------------------------------------------*/

    if(min !== undefined && max !== undefined)
    {
        return [min, max];
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    return [fallbackMin, fallbackMax];

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const updateRangesCache = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const xRange = getRange('x-min', 'x-max', -1, 1);
    const yRange = getRange('y-min', 'y-max', -1, 1);
    const zRange = getRange('z-min', 'z-max', -1, 1);

    /*----------------------------------------------------------------------------------------------------------------*/

    const key = `${xRange[0]}:${xRange[1]}|${yRange[0]}:${yRange[1]}|${zRange[0]}:${zRange[1]}`;

    /*----------------------------------------------------------------------------------------------------------------*/

    cachedRanges = {xRange: xRange, yRange: yRange, zRange: zRange};

    /*----------------------------------------------------------------------------------------------------------------*/

    if(lastRangesKey !== key)
    {
        lastRangesKey = key;
        cachedFrameXYZ = null;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    return key;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const clamp = (v, vmin, vmax) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(v < vmin)
    {
        return vmin;
    }

    if(v > vmax)
    {
        return vmax;
    }

    return v;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const clampPoint = (x, y, z) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const xr = cachedRanges.xRange;
    const yr = cachedRanges.yRange;
    const zr = cachedRanges.zRange;

    /*----------------------------------------------------------------------------------------------------------------*/

    return {
        x: clamp(x, xr[0], xr[1]),
        y: clamp(y, yr[0], yr[1]),
        z: clamp(z, zr[0], zr[1]),
    };

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const buildFrameTraces = (xRange, yRange, zRange) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const x0 = xRange[0];
    const x1 = xRange[1];

    const y0 = yRange[0];
    const y1 = yRange[1];

    const z0 = zRange[0];
    const z1 = zRange[1];

    /*----------------------------------------------------------------------------------------------------------------*/

    const mkLine = (x, y, z) => ({
        id: '__frame__',
        name: '',
        type: 'scatter3d',
        mode: 'lines',
        x: x,
        y: y,
        z: z,
        hoverinfo: 'skip',
        showlegend: false,
        line: {
            width: 2,
        },
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    return [
        mkLine([x0, x1], [y0, y0], [z0, z0]),
        mkLine([x1, x1], [y0, y1], [z0, z0]),
        mkLine([x1, x0], [y1, y1], [z0, z0]),
        mkLine([x0, x0], [y1, y0], [z0, z0]),

        mkLine([x0, x1], [y0, y0], [z1, z1]),
        mkLine([x1, x1], [y0, y1], [z1, z1]),
        mkLine([x1, x0], [y1, y1], [z1, z1]),
        mkLine([x0, x0], [y1, y0], [z1, z1]),

        mkLine([x0, x0], [y0, y0], [z0, z1]),
        mkLine([x1, x1], [y0, y0], [z0, z1]),
        mkLine([x1, x1], [y1, y1], [z0, z1]),
        mkLine([x0, x0], [y1, y1], [z0, z1]),
    ];

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const getFrameXYZ = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(cachedFrameXYZ !== null)
    {
        return cachedFrameXYZ;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const frame = buildFrameTraces(cachedRanges.xRange, cachedRanges.yRange, cachedRanges.zRange);

    /*----------------------------------------------------------------------------------------------------------------*/

    cachedFrameXYZ = {
        xs: frame.map((t) => t.x),
        ys: frame.map((t) => t.y),
        zs: frame.map((t) => t.z),
    };

    /*----------------------------------------------------------------------------------------------------------------*/

    return cachedFrameXYZ;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const buildLayout = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const xr = cachedRanges.xRange;
    const yr = cachedRanges.yRange;
    const zr = cachedRanges.zRange;

    /*----------------------------------------------------------------------------------------------------------------*/

    const layout = {
        autosize: true,
        uirevision: 1,

        hovermode: false,

        margin: {
            l: 0,
            r: 0,
            b: 0,
            t: 0,
            pad: 0,
        },

        showlegend: false,

        scene: {
            uirevision: 1,
            aspectmode: 'cube',

            domain: {
                x: [0.0, 1.0],
                y: [0.0, 1.0],
            },

            xaxis: {
                title: {
                    text: '',
                },
                range: xr,
                showgrid: true,
                showline: true,
                ticks: 'outside',
                zeroline: false,
            },

            yaxis: {
                title: {
                    text: '',
                },
                range: yr,
                showgrid: true,
                showline: true,
                ticks: 'outside',
                zeroline: false,
            },

            zaxis: {
                title: {
                    text: '',
                },
                range: zr,
                showgrid: true,
                showline: true,
                ticks: 'outside',
                zeroline: false,
            },
        },
    };

    /*----------------------------------------------------------------------------------------------------------------*/

    if(lastCamera !== null)
    {
        layout.scene.camera = lastCamera;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    return layout;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const applyCamera = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null || lastCamera === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.relayout(plotEl.value, {'scene.camera': lastCamera});

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const updateFrame = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const {xs, ys, zs} = getFrameXYZ();

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.restyle(plotEl.value, {x: xs, y: ys, z: zs}, [...Array(FRAME_TRACE_COUNT).keys()]);

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const applyOptions = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const prevKey = lastRangesKey;

    updateRangesCache();

    /*----------------------------------------------------------------------------------------------------------------*/

    if(prevKey === lastRangesKey)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const xr = cachedRanges.xRange;
    const yr = cachedRanges.yRange;
    const zr = cachedRanges.zRange;

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.relayout(plotEl.value, {
        'scene.xaxis.range': xr,
        'scene.yaxis.range': yr,
        'scene.zaxis.range': zr,
    }).then(() => {

        updateFrame();
        applyCamera();
    });

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const flushPending = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    flushScheduled = false;

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const traceIndices = [];
    const xs = [];
    const ys = [];
    const zs = [];

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    for(let i = 0; i < n; i++)
    {
        const px = pendingX[i];

        if(px && px.length > 0)
        {
            traceIndices.push(FRAME_TRACE_COUNT + i);

            xs.push(px.splice(0, px.length));
            ys.push(pendingY[i].splice(0, pendingY[i].length));
            zs.push(pendingZ[i].splice(0, pendingZ[i].length));
        }
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    if(traceIndices.length === 0)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.extendTraces(plotEl.value, {x: xs, y: ys, z: zs}, traceIndices, props.maxPoints);

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const scheduleFlush = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(flushScheduled)
    {
        return;
    }

    flushScheduled = true;

    /*----------------------------------------------------------------------------------------------------------------*/

    requestAnimationFrame(() => {

        flushPending();
    });

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const enqueuePoint = (i, x, y, z) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(enabledByIndex[i] !== true)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const p = clampPoint(x, y, z);

    /*----------------------------------------------------------------------------------------------------------------*/

    pendingX[i].push(p.x);
    pendingY[i].push(p.y);
    pendingZ[i].push(p.z);

    /*----------------------------------------------------------------------------------------------------------------*/

    scheduleFlush();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const bindCameraListener = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    plotEl.value.removeAllListeners?.('plotly_relayout');

    /*----------------------------------------------------------------------------------------------------------------*/

    plotEl.value.on?.('plotly_relayout', (ev) => {

        if(ev && ev['scene.camera'])
        {
            lastCamera = ev['scene.camera'];

            return;
        }

        if(plotEl.value?.layout?.scene?.camera)
        {
            lastCamera = plotEl.value.layout.scene.camera;
        }
    });

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initDatasets = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    lastVals1.clear();
    lastVals2.clear();
    lastVals3.clear();

    /*----------------------------------------------------------------------------------------------------------------*/

    flushScheduled = false;

    /*----------------------------------------------------------------------------------------------------------------*/

    updateRangesCache();

    /*----------------------------------------------------------------------------------------------------------------*/

    const traces = [...buildFrameTraces(cachedRanges.xRange, cachedRanges.yRange, cachedRanges.zRange)];

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    enabledByIndex.length = 0;

    pendingX.length = 0;
    pendingY.length = 0;
    pendingZ.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/

    for(let i = 0; i < n; i++)
    {
        const v1 = props.variables1[i];
        const v2 = props.variables2[i];
        const v3 = props.variables3[i];

        const id = `${v1} / ${v2} / ${v3}`;
        const enabled = (props.enabled[id] ? true : false);

        /*------------------------------------------------------------------------------------------------------------*/

        traces.push({
            id: id,
            name: '',
            type: 'scatter3d',
            mode: 'markers',

            x: [],
            y: [],
            z: [],

            hoverinfo: 'skip',
            showlegend: false,

            marker: {
                size: 3,
                opacity: 0.8,
            },

            visible: enabled,
        });

        /*------------------------------------------------------------------------------------------------------------*/

        enabledByIndex[i] = enabled;

        pendingX[i] = [];
        pendingY[i] = [];
        pendingZ[i] = [];

        lastVals1.set(i, undefined);
        lastVals2.set(i, undefined);
        lastVals3.set(i, undefined);

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.react(plotEl.value, traces, buildLayout(), {
        displayModeBar: false,
        responsive: true,
    }).then(() => {

        /*------------------------------------------------------------------------------------------------------------*/

        bindCameraListener();

        initWatches();

        /*------------------------------------------------------------------------------------------------------------*/

        Plotly.Plots.resize(plotEl.value);

        /*------------------------------------------------------------------------------------------------------------*/
    });

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    /*----------------------------------------------------------------------------------------------------------------*/

    for(let i = 0; i < n; i++)
    {
        const var1 = props.variables1[i];
        const var2 = props.variables2[i];
        const var3 = props.variables3[i];

        /*------------------------------------------------------------------------------------------------------------*/

        const plotIfReady = () => {

            /*--------------------------------------------------------------------------------------------------------*/

            if(plotEl.value === null)
            {
                return;
            }

            /*--------------------------------------------------------------------------------------------------------*/

            const x = lastVals2.get(i);
            const y = lastVals1.get(i);
            const z = lastVals3.get(i);

            /*--------------------------------------------------------------------------------------------------------*/

            if(x !== undefined && y !== undefined && z !== undefined)
            {
                enqueuePoint(i, x, y, z);
            }

            /*--------------------------------------------------------------------------------------------------------*/
        };

        /*------------------------------------------------------------------------------------------------------------*/

        const def1 = nyxStore.resolve(var1);

        if(def1 !== undefined)
        {
            stops.push(watch(() => def1.$, () => {

                /*----------------------------------------------------------------------------------------------------*/

                const val = nyxStore.getValue(def1);

                if(val !== undefined)
                {
                    lastVals1.set(i, val);

                    plotIfReady();
                }

                /*----------------------------------------------------------------------------------------------------*/

            }, {immediate: true}));
        }

        /*------------------------------------------------------------------------------------------------------------*/

        const def2 = nyxStore.resolve(var2);

        if(def2 !== undefined)
        {
            stops.push(watch(() => def2.$, () => {

                /*----------------------------------------------------------------------------------------------------*/

                const val = nyxStore.getValue(def2);

                if(val !== undefined)
                {
                    lastVals2.set(i, val);

                    plotIfReady();
                }

                /*----------------------------------------------------------------------------------------------------*/

            }, {immediate: true}));
        }

        /*------------------------------------------------------------------------------------------------------------*/

        const def3 = nyxStore.resolve(var3);

        if(def3 !== undefined)
        {
            stops.push(watch(() => def3.$, () => {

                /*----------------------------------------------------------------------------------------------------*/

                const val = nyxStore.getValue(def3);

                if(val !== undefined)
                {
                    lastVals3.set(i, val);

                    plotIfReady();
                }

                /*----------------------------------------------------------------------------------------------------*/

            }, {immediate: true}));
        }

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initTitles = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.relayout(plotEl.value, {
        'scene.xaxis.title.text': props.title2 || 'X value',
        'scene.yaxis.title.text': props.title1 || 'Y value',
        'scene.zaxis.title.text': props.title3 || 'Z value',
    });

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initEnabled = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const visible = [];

    for(let i = 0; i < plotEl.value.data.length; i++)
    {
        const trace = plotEl.value.data[i];

        if(i < FRAME_TRACE_COUNT)
        {
            visible.push(true);

            continue;
        }

        const enabled = (props.enabled[trace.id] ? true : false);

        enabledByIndex[i - FRAME_TRACE_COUNT] = enabled;

        visible.push(enabled);
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.restyle(plotEl.value, {visible: visible});

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    updateRangesCache();

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.newPlot(plotEl.value, [], buildLayout(), {
        displayModeBar: false,
        responsive: true,
    }).then(() => {

        /*------------------------------------------------------------------------------------------------------------*/

        resizeObserver = new ResizeObserver(() => {

            Plotly.Plots.resize(plotEl.value);
        });

        resizeObserver.observe(plotEl.value);

        /*------------------------------------------------------------------------------------------------------------*/

        watch([() => props.variables1, () => props.variables2, () => props.variables3], initDatasets, {immediate: true, deep: false});

        /*------------------------------------------------------------------------------------------------------------*/

        watch([() => props.title1, () => props.title2, () => props.title3], initTitles, {immediate: true, deep: false});

        /*------------------------------------------------------------------------------------------------------------*/

        watch(() => props.enabled, initEnabled, {immediate: true, deep: true});

        /*------------------------------------------------------------------------------------------------------------*/

        watch(() => props.options, applyOptions, {immediate: false, deep: true});

        /*------------------------------------------------------------------------------------------------------------*/
    });

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/

onBeforeUnmount(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    if(resizeObserver)
    {
        resizeObserver.disconnect();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value)
    {
        Plotly.purge(plotEl.value);
    }

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <div class="h-100 w-100" ref="plotEl"></div>

    <!-- *********************************************************************************************************** -->

</template>
