<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, watch, onMounted, onBeforeUnmount} from 'vue';

import {useNyxStore} from 'vue-nyx';

import Plotly from 'plotly.js-dist-min';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    variables1: {
        type: Array,
        required: true,
    },
    variables2: {
        type: Array,
        required: true,
    },
    variables3: {
        type: Array,
        required: true,
    },
    enabled: {
        type: Object,
        required: true,
    },
    maxPoints: {
        type: Number,
        required: true,
    },
    options: {
        type: Object,
        required: true,
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const plotEl = ref(null);

/*--------------------------------------------------------------------------------------------------------------------*/

let resizeObserver = null;

/*--------------------------------------------------------------------------------------------------------------------*/

const stops = [];

/*--------------------------------------------------------------------------------------------------------------------*/

const lastVals1 = new Map();
const lastVals2 = new Map();
const lastVals3 = new Map();

/*--------------------------------------------------------------------------------------------------------------------*/

const FRAME_TRACE_COUNT = 12;

/*--------------------------------------------------------------------------------------------------------------------*/

let lastCamera = null;

/*--------------------------------------------------------------------------------------------------------------------*/

let lastRanges = null;

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const getN = () => Math.min(props.variables1.length, props.variables2.length, props.variables3.length);

/*--------------------------------------------------------------------------------------------------------------------*/

const stopWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const stop of stops)
    {
        stop();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stops.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const getRange = (minKey, maxKey, fallbackMin, fallbackMax) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const min = props.options[minKey];
    const max = props.options[maxKey];

    /*----------------------------------------------------------------------------------------------------------------*/

    if(min !== undefined && max !== undefined)
    {
        return [min, max];
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    return [fallbackMin, fallbackMax];

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const getRanges = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const xRange = getRange('x-min', 'x-max', -1, 1);
    const yRange = getRange('y-min', 'y-max', -1, 1);
    const zRange = getRange('z-min', 'z-max', -1, 1);

    /*----------------------------------------------------------------------------------------------------------------*/

    return {xRange: xRange, yRange: yRange, zRange: zRange};

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const buildFrameTraces = (xRange, yRange, zRange) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const x0 = xRange[0];
    const x1 = xRange[1];

    const y0 = yRange[0];
    const y1 = yRange[1];

    const z0 = zRange[0];
    const z1 = zRange[1];

    /*----------------------------------------------------------------------------------------------------------------*/

    const mkLine = (x, y, z) => ({
        id: '__frame__',
        name: '',
        type: 'scatter3d',
        mode: 'lines',
        x: x,
        y: y,
        z: z,
        hoverinfo: 'skip',
        showlegend: false,
        line: {
            width: 2,
        },
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    const traces = [];

    /*----------------------------------------------------------------------------------------------------------------*/
    /* Bottom rectangle (z = z0)                                                                                      */
    /*----------------------------------------------------------------------------------------------------------------*/

    traces.push(mkLine([x0, x1], [y0, y0], [z0, z0]));
    traces.push(mkLine([x1, x1], [y0, y1], [z0, z0]));
    traces.push(mkLine([x1, x0], [y1, y1], [z0, z0]));
    traces.push(mkLine([x0, x0], [y1, y0], [z0, z0]));

    /*----------------------------------------------------------------------------------------------------------------*/
    /* Top rectangle (z = z1)                                                                                         */
    /*----------------------------------------------------------------------------------------------------------------*/

    traces.push(mkLine([x0, x1], [y0, y0], [z1, z1]));
    traces.push(mkLine([x1, x1], [y0, y1], [z1, z1]));
    traces.push(mkLine([x1, x0], [y1, y1], [z1, z1]));
    traces.push(mkLine([x0, x0], [y1, y0], [z1, z1]));

    /*----------------------------------------------------------------------------------------------------------------*/
    /* Vertical edges                                                                                                  */
    /*----------------------------------------------------------------------------------------------------------------*/

    traces.push(mkLine([x0, x0], [y0, y0], [z0, z1]));
    traces.push(mkLine([x1, x1], [y0, y0], [z0, z1]));
    traces.push(mkLine([x1, x1], [y1, y1], [z0, z1]));
    traces.push(mkLine([x0, x0], [y1, y1], [z0, z1]));

    /*----------------------------------------------------------------------------------------------------------------*/

    return traces;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const buildLayout = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const {xRange, yRange, zRange} = getRanges();

    /*----------------------------------------------------------------------------------------------------------------*/

    return {
        autosize: true,
        uirevision: 1,

        /*----------------------------------------------------------------------------------------------------------------*/
        /* Disable hover / infolayer                                                                                    */
        /*----------------------------------------------------------------------------------------------------------------*/

        hovermode: false,

        /*----------------------------------------------------------------------------------------------------------------*/
        /* Maximize usable space                                                                                        */
        /*----------------------------------------------------------------------------------------------------------------*/

        margin: {
            l: 0,
            r: 0,
            b: 0,
            t: 0,
            pad: 0,
        },

        showlegend: false,

        scene: {
            /* IMPORTANT: keep UI state stable for this subplot too */
            uirevision: 1,

            aspectmode: 'cube',

            domain: {
                x: [0.0, 1.0],
                y: [0.0, 1.0],
            },

            xaxis: {
                title: '',
                range: xRange,
                showgrid: true,
                showline: true,
                ticks: 'outside',
                zeroline: false,
            },

            yaxis: {
                title: '',
                range: yRange,
                showgrid: true,
                showline: true,
                ticks: 'outside',
                zeroline: false,
            },

            zaxis: {
                title: '',
                range: zRange,
                showgrid: true,
                showline: true,
                ticks: 'outside',
                zeroline: false,
            },
        },
    };

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const applyCamera = async () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null || lastCamera === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    await Plotly.relayout(plotEl.value, {'scene.camera': lastCamera});

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const updateFrame = async () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const {xRange, yRange, zRange} = getRanges();

    const frame = buildFrameTraces(xRange, yRange, zRange);

    /*----------------------------------------------------------------------------------------------------------------*/

    const xs = [];
    const ys = [];
    const zs = [];

    for(const t of frame)
    {
        xs.push(t.x);
        ys.push(t.y);
        zs.push(t.z);
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    await Plotly.restyle(plotEl.value, {x: xs, y: ys, z: zs}, [...Array(FRAME_TRACE_COUNT).keys()]);

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const applyOptions = async () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const {xRange, yRange, zRange} = getRanges();

    const newRanges = `${xRange[0]}:${xRange[1]}|${yRange[0]}:${yRange[1]}|${zRange[0]}:${zRange[1]}`;

    /*----------------------------------------------------------------------------------------------------------------*/

    if(lastRanges === newRanges)
    {
        return;
    }

    lastRanges = newRanges;

    /*----------------------------------------------------------------------------------------------------------------*/
    /* Update ranges only (do NOT rebuild traces => do NOT reset zoom)                                                 */
    /*----------------------------------------------------------------------------------------------------------------*/

    await Plotly.relayout(plotEl.value, {
        'scene.xaxis.range': xRange,
        'scene.yaxis.range': yRange,
        'scene.zaxis.range': zRange,
    });

    /*----------------------------------------------------------------------------------------------------------------*/
    /* Update the cube frame lines to match new ranges                                                                 */
    /*----------------------------------------------------------------------------------------------------------------*/

    await updateFrame();

    /*----------------------------------------------------------------------------------------------------------------*/
    /* Restore camera if needed                                                                                        */
    /*----------------------------------------------------------------------------------------------------------------*/

    await applyCamera();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initDatasets = async () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    lastVals1.clear();
    lastVals2.clear();
    lastVals3.clear();

    /*----------------------------------------------------------------------------------------------------------------*/

    const {xRange, yRange, zRange} = getRanges();

    lastRanges = `${xRange[0]}:${xRange[1]}|${yRange[0]}:${yRange[1]}|${zRange[0]}:${zRange[1]}`;

    /*----------------------------------------------------------------------------------------------------------------*/

    const traces = [];

    /*----------------------------------------------------------------------------------------------------------------*/
    /* Cube frame                                                                                                     */
    /*----------------------------------------------------------------------------------------------------------------*/

    for(const t of buildFrameTraces(xRange, yRange, zRange))
    {
        traces.push(t);
    }

    /*----------------------------------------------------------------------------------------------------------------*/
    /* Data traces                                                                                                    */
    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    /*----------------------------------------------------------------------------------------------------------------*/

    for(let i = 0; i < n; i++)
    {
        const v1 = props.variables1[i];
        const v2 = props.variables2[i];
        const v3 = props.variables3[i];

        const id = `${v1} / ${v2} / ${v3}`;

        /*------------------------------------------------------------------------------------------------------------*/

        traces.push({
            id: id,

            name: `${v1.split(':').pop()} / ${v2.split(':').pop()} / ${v3.split(':').pop()}`,

            type: 'scatter3d',
            mode: 'markers',

            x: [],
            y: [],
            z: [],

            hoverinfo: 'skip',
            showlegend: false,

            marker: {
                size: 3,
                opacity: 0.8,
            },

            visible: (props.enabled[id] ? true : 'legendonly'),
        });

        /*------------------------------------------------------------------------------------------------------------*/

        lastVals1.set(i, undefined);
        lastVals2.set(i, undefined);
        lastVals3.set(i, undefined);

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    await Plotly.react(plotEl.value, traces, buildLayout(), {
        displayModeBar: false,
        responsive: true,
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value)
    {
        plotEl.value.removeAllListeners?.('plotly_relayout');

        plotEl.value.on?.('plotly_relayout', () => {

            if(plotEl.value && plotEl.value.layout && plotEl.value.layout.scene)
            {
                lastCamera = plotEl.value.layout.scene.camera;
            }
        });
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    initWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.Plots.resize(plotEl.value);

    /*----------------------------------------------------------------------------------------------------------------*/

    await applyCamera();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    /*----------------------------------------------------------------------------------------------------------------*/

    for(let i = 0; i < n; i++)
    {
        const var1 = props.variables1[i];
        const var2 = props.variables2[i];
        const var3 = props.variables3[i];

        /*------------------------------------------------------------------------------------------------------------*/

        const plotIfReady = () => {

            /*--------------------------------------------------------------------------------------------------------*/

            if(plotEl.value === null)
            {
                return;
            }

            /*--------------------------------------------------------------------------------------------------------*/

            const x = lastVals2.get(i);
            const y = lastVals1.get(i);
            const z = lastVals3.get(i);

            /*--------------------------------------------------------------------------------------------------------*/

            if(x !== undefined && y !== undefined && z !== undefined)
            {
                Plotly.extendTraces(
                    plotEl.value,
                    {
                        x: [[x]],
                        y: [[y]],
                        z: [[z]],
                    },
                    [FRAME_TRACE_COUNT + i],
                    props.maxPoints
                );
            }

            /*--------------------------------------------------------------------------------------------------------*/
        };

        /*------------------------------------------------------------------------------------------------------------*/

        const def1 = nyxStore.resolve(var1);

        if(def1 !== undefined)
        {
            stops.push(watch(() => def1.$, () => {

                /*----------------------------------------------------------------------------------------------------*/

                const val = nyxStore.getValue(def1);

                if(val !== undefined)
                {
                    lastVals1.set(i, val);

                    plotIfReady();
                }

                /*----------------------------------------------------------------------------------------------------*/

            }, {immediate: true}));
        }

        /*------------------------------------------------------------------------------------------------------------*/

        const def2 = nyxStore.resolve(var2);

        if(def2 !== undefined)
        {
            stops.push(watch(() => def2.$, () => {

                /*----------------------------------------------------------------------------------------------------*/

                const val = nyxStore.getValue(def2);

                if(val !== undefined)
                {
                    lastVals2.set(i, val);

                    plotIfReady();
                }

                /*----------------------------------------------------------------------------------------------------*/

            }, {immediate: true}));
        }

        /*------------------------------------------------------------------------------------------------------------*/

        const def3 = nyxStore.resolve(var3);

        if(def3 !== undefined)
        {
            stops.push(watch(() => def3.$, () => {

                /*----------------------------------------------------------------------------------------------------*/

                const val = nyxStore.getValue(def3);

                if(val !== undefined)
                {
                    lastVals3.set(i, val);

                    plotIfReady();
                }

                /*----------------------------------------------------------------------------------------------------*/

            }, {immediate: true}));
        }

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initEnabled = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value === null)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    const visible = [];

    for(let i = 0; i < plotEl.value.data.length; i++)
    {
        const trace = plotEl.value.data[i];

        if(i < FRAME_TRACE_COUNT)
        {
            visible.push(true);

            continue;
        }

        visible.push(props.enabled[trace.id] ? true : 'legendonly');
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    Plotly.restyle(plotEl.value, {visible: visible});

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(async () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    await Plotly.newPlot(plotEl.value, [], buildLayout(), {
        displayModeBar: false,
        responsive: true,
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    resizeObserver = new ResizeObserver(async () => {

        /*------------------------------------------------------------------------------------------------------------*/

        Plotly.Plots.resize(plotEl.value);

        /*------------------------------------------------------------------------------------------------------------*/

        await applyCamera();

        /*------------------------------------------------------------------------------------------------------------*/
    });

    resizeObserver.observe(plotEl.value);

    /*----------------------------------------------------------------------------------------------------------------*/

    watch([() => props.variables1, () => props.variables2, () => props.variables3], initDatasets, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.enabled, initEnabled, {immediate: true, deep: true});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.options, applyOptions, {immediate: false, deep: true});

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/

onBeforeUnmount(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    if(resizeObserver)
    {
        resizeObserver.disconnect();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    if(plotEl.value)
    {
        Plotly.purge(plotEl.value);
    }

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <div class="h-100 w-100" ref="plotEl"></div>

    <!-- *********************************************************************************************************** -->

</template>
