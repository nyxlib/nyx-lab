<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, watch, onMounted, onBeforeUnmount} from 'vue';

import {useNyxStore} from 'vue-nyx';

import * as echarts from 'echarts';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    variables1: {
        type: Array,
        required: true,
    },
    variables2: {
        type: Array,
        required: true,
    },
    variables3: {
        type: Array,
        required: true,
    },
    title1: {
        type: String,
        default: null,
    },
    title2: {
        type: String,
        default: null,
    },
    title3: {
        type: String,
        default: null,
    },
    enabled: {
        type: Object,
        required: true,
    },
    maxPoints: {
        type: Number,
        required: true,
    },
    options: {
        type: Object,
        required: true,
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const plotEl = ref(null);

let chartInstance = null;

let resizeObserver = null;

/*--------------------------------------------------------------------------------------------------------------------*/

const stops = [];

const seriesData = [];

const enabledByIndex = [];

/*--------------------------------------------------------------------------------------------------------------------*/

const lastVals1 = [];
const lastVals2 = [];
const lastVals3 = [];

/*--------------------------------------------------------------------------------------------------------------------*/

let flushScheduled = false;

/*--------------------------------------------------------------------------------------------------------------------*/

const pendingX = [];
const pendingY = [];
const pendingZ = [];

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const getN = () => Math.min(props.variables1.length, props.variables2.length, props.variables3.length);

/*--------------------------------------------------------------------------------------------------------------------*/

const getSeriesId = (i) => `${props.variables1[i]} / ${props.variables2[i]} / ${props.variables3[i]}`;

/*--------------------------------------------------------------------------------------------------------------------*/

const getCssVar = (name) => getComputedStyle(document.documentElement).getPropertyValue(name).trim();

/*--------------------------------------------------------------------------------------------------------------------*/

const toFiniteNumber = (v) => {

    const x = (typeof v === 'string') ? Number(v) : v;

    return Number.isFinite(x) ? x : undefined;
};

/*--------------------------------------------------------------------------------------------------------------------*/

const getAxisOption = (name, minKey, maxKey) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const textColor = getCssVar('--bs-body-color');

    const borderColor = getCssVar('--bs-border-color');

    /*----------------------------------------------------------------------------------------------------------------*/

    const out = {
        type: 'value',
        name: name,
        nameTextStyle: {
            color: textColor,
            fontFamily: 'var(--bs-body-font-family)',
        },
        axisLabel: {
            color: textColor,
            fontFamily: 'var(--bs-body-font-family)',
        },
        axisLine: {
            lineStyle: {
                width: 1,
                color: borderColor,
            },
        },
        axisTick: {
            lineStyle: {
                width: 1,
                color: borderColor,
            },
        },
        splitLine: {
            lineStyle: {
                width: 1,
                color: borderColor,
            },
        },
        axisPointer: {
            lineStyle: {
                width: 1,
                opacity: 0.5,
                color: borderColor,
            },
            label: {
                show: false,
            },
        },
    };

    /*----------------------------------------------------------------------------------------------------------------*/

    const min = toFiniteNumber(props.options[minKey]);
    const max = toFiniteNumber(props.options[maxKey]);

    /*----------------------------------------------------------------------------------------------------------------*/

    if(min !== undefined) {
        out.min = min;
    }

    if(max !== undefined) {
        out.max = max;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    return out;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const getAxesOption = () => ({
    xAxis3D: getAxisOption(props.title2 || 'X value', 'x-min', 'x-max'),
    yAxis3D: getAxisOption(props.title1 || 'Y value', 'y-min', 'y-max'),
    zAxis3D: getAxisOption(props.title3 || 'Z value', 'z-min', 'z-max'),
});

/*--------------------------------------------------------------------------------------------------------------------*/

const getSeriesData = (i) => enabledByIndex[i] ? seriesData[i] : [];

/*--------------------------------------------------------------------------------------------------------------------*/

const buildSeriesList = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const out = [];

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    for(let i = 0; i < n; i++)
    {
        out.push({
            id: getSeriesId(i),
            type: 'scatter3D',
            name: '',
            symbolSize: 5,
            data: getSeriesData(i),
        });
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    return out;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const buildOption = () => ({
    animation: false,
    tooltip: {
        show: false,
    },
    ...getAxesOption(),
    grid3D: {
        viewControl: {
            projection: 'perspective',
            zoomSensitivity: 3.0,
        },
    },
    series: buildSeriesList(),
});

/*--------------------------------------------------------------------------------------------------------------------*/

const setChartOption = (option, notMerge = false) => {

    chartInstance.setOption(option, {
        notMerge: notMerge,
        lazyUpdate: true,
    });
};

/*--------------------------------------------------------------------------------------------------------------------*/

const stopWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const stop of stops)
    {
        stop();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stops.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const resetSeriesState = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    lastVals1.length = 0;
    lastVals2.length = 0;
    lastVals3.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/

    flushScheduled = false;

    /*----------------------------------------------------------------------------------------------------------------*/

    seriesData.length = 0;

    enabledByIndex.length = 0;

    pendingX.length = 0;
    pendingY.length = 0;
    pendingZ.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    for(let i = 0; i < n; i++)
    {
        const id = getSeriesId(i);

        /*------------------------------------------------------------------------------------------------------------*/

        seriesData[i] = [];

        enabledByIndex[i] = (!!props.enabled[id]);

        pendingX[i] = [];
        pendingY[i] = [];
        pendingZ[i] = [];

        lastVals1[i] = undefined;
        lastVals2[i] = undefined;
        lastVals3[i] = undefined;

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const scheduleFlush = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(flushScheduled)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    flushScheduled = true;

    requestAnimationFrame(() => {

        flushScheduled = false;

        flushPending();
    });

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const enqueuePoint = (i, x, y, z) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(enabledByIndex[i] !== true)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    pendingX[i].push(x);
    pendingY[i].push(y);
    pendingZ[i].push(z);

    /*----------------------------------------------------------------------------------------------------------------*/

    scheduleFlush();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const flushPending = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const series = [];

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    for(let i = 0; i < n; i++)
    {
        const px = pendingX[i];

        if(px.length === 0)
        {
            continue;
        }

        const py = pendingY[i];
        const pz = pendingZ[i];
        const dst = seriesData[i];

        /*------------------------------------------------------------------------------------------------------------*/

        for(let j = 0; j < px.length; j++)
        {
            dst.push([px[j], py[j], pz[j]]);
        }

        /*------------------------------------------------------------------------------------------------------------*/

        const extra = dst.length - props.maxPoints;

        if(extra > 0)
        {
            dst.splice(0, extra);
        }

        /*------------------------------------------------------------------------------------------------------------*/

        px.length = 0;
        py.length = 0;
        pz.length = 0;

        /*------------------------------------------------------------------------------------------------------------*/

        series.push({
            id: getSeriesId(i),
            data: getSeriesData(i),
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    if(series.length > 0)
    {
        setChartOption({series: series});
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const watchVariable = (variable, values, i, plotIfReady) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const def = nyxStore.resolve(variable);

    /*----------------------------------------------------------------------------------------------------------------*/

    if(def === undefined)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stops.push(watch(() => def.$, () => {

        const val = nyxStore.getValue(def);

        if(val !== undefined)
        {
            values[i] = val;

            plotIfReady();
        }

    }, {immediate: true}));

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    /*----------------------------------------------------------------------------------------------------------------*/

    for(let i = 0; i < n; i++)
    {
        const plotIfReady = () => {

            const x = lastVals2[i];
            const y = lastVals1[i];
            const z = lastVals3[i];

            /*--------------------------------------------------------------------------------------------------------*/

            if(x !== undefined && y !== undefined && z !== undefined)
            {
                enqueuePoint(i, x, y, z);
            }

            /*--------------------------------------------------------------------------------------------------------*/
        };

        /*------------------------------------------------------------------------------------------------------------*/

        watchVariable(props.variables1[i], lastVals1, i, plotIfReady);
        watchVariable(props.variables2[i], lastVals2, i, plotIfReady);
        watchVariable(props.variables3[i], lastVals3, i, plotIfReady);

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initDatasets = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    resetSeriesState();

    setChartOption(buildOption(), true);

    initWatches();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initTitles = () => {

    setChartOption(getAxesOption());
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initEnabled = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const series = [];

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = getN();

    for(let i = 0; i < n; i++)
    {
        const id = getSeriesId(i);

        /*------------------------------------------------------------------------------------------------------------*/

        enabledByIndex[i] = (!!props.enabled[id]);

        /*------------------------------------------------------------------------------------------------------------*/

        series.push({
            id: id,
            data: getSeriesData(i),
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    setChartOption({series: series});

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const applyOptions = () => {

    setChartOption(getAxesOption());
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance = echarts.init(plotEl.value);

    /*----------------------------------------------------------------------------------------------------------------*/

    setChartOption(buildOption(), true);

    /*----------------------------------------------------------------------------------------------------------------*/

    resizeObserver = new ResizeObserver(() => {

        chartInstance.resize();
    });

    resizeObserver.observe(plotEl.value);

    /*----------------------------------------------------------------------------------------------------------------*/

    watch([() => props.variables1, () => props.variables2, () => props.variables3], initDatasets, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch([() => props.title1, () => props.title2, () => props.title3], initTitles, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.enabled, initEnabled, {immediate: true, deep: true});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.options, applyOptions, {immediate: false, deep: true});

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/

onBeforeUnmount(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    resizeObserver?.disconnect();

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance?.dispose();

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <div class="h-100 w-100" ref="plotEl"></div>

    <!-- *********************************************************************************************************** -->

</template>
