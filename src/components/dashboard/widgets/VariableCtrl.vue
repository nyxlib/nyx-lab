<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, watch, onMounted, onBeforeUnmount} from 'vue';

import {useNyxStore} from 'vue-nyx';

import {Chart} from 'chart.js/auto';

/*--------------------------------------------------------------------------------------------------------------------*/

import 'chartjs-adapter-date-fns';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    variables1: {
        type: Object,
        required: true,
    },
    enabled: {
        type: Object,
        required: true,
    },
    period: {
        type: Number,
        required: true,
    },
    options: {
        type: Object,
        required: true,
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const canvasEl = ref(null);

let chart = null;

let interval = null;

/*--------------------------------------------------------------------------------------------------------------------*/

let datasets = {};
let lastVals = {};

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const initDatasets = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    datasets = {};
    lastVals = {};

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.data.datasets = props.variables1.filter((variable) => props.enabled[variable]).map((variable) => {

        const dataset = {
            data: [],
            label: variable,
        };

        datasets[variable] =  dataset ;
        lastVals[variable] = undefined;

        return dataset;
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initAcqui = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(props.period > 0)
    {
        clearInterval(interval);

        interval = setInterval(() => {

            const now = Date.now();

            for(const variable of props.variables1)
            {
                /*----------------------------------------------------------------------------------------------------*/

                const def = nyxStore.resolve(variable);

                /*----------------------------------------------------------------------------------------------------*/

                let val;

                switch(def['<>'])
                {
                    /*------------------------------------------------------------------------------------------------*/

                    case 'defText':
                        val = def.$;
                        break;

                    /*------------------------------------------------------------------------------------------------*/

                    case 'defNumber':
                        val = Number.parseFloat(def.$);
                        break;

                    /*------------------------------------------------------------------------------------------------*/

                    case 'defLight':
                        switch(def.$)
                        {
                            case 'Idle':
                                val = 0;
                                break;

                            case 'Ok':
                                val = 1;
                                break;

                            case 'Busy':
                                val = 2;
                                break;

                            case 'Alert':
                                val = 3;
                                break;

                            default:
                                continue;
                        }
                        break;

                    /*------------------------------------------------------------------------------------------------*/

                    case 'defSwitch':
                        val = def.$ === 'Off' ? 0 : 1;
                        break;

                    /*------------------------------------------------------------------------------------------------*/

                    default:
                        continue;

                    /*------------------------------------------------------------------------------------------------*/
                }

                /*----------------------------------------------------------------------------------------------------*/

                const dataset = datasets[variable];

                if(dataset)
                {
                    /*------------------------------------------------------------------------------------------------*/

                    if(dataset.data.length < 2
                       ||
                       lastVals[variable] !== val
                    ) {
                        lastVals[variable] = val;

                        dataset.data.push({
                            x: now,
                            y: val,
                        });
                    }
                    else
                    {
                        dataset.data[dataset.data.length - 1].x = now;
                    }

                    /*------------------------------------------------------------------------------------------------*/

                    dataset.hidden = !props.enabled[variable];

                    /*------------------------------------------------------------------------------------------------*/
                }

                /*----------------------------------------------------------------------------------------------------*/
            }

            chart.update('none');

        }, props.period);
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chart = new Chart(canvasEl.value, {
        type: 'line',
        data: {
            labels: [],
            datasets: []
        },
        options: {
            animation: false,
            responsive: true,
            maintainAspectRatio: false,
            elements: {
                line: {
                    borderWidth: 1,
                    tension: 0.1
                },
                point: {
                    radius: 0,
                    hitRadius: 0,
                    hoverRadius: 0
                }
            },
            scales: {
                x: {
                    type: 'time',
                    time: {
                        displayFormats: {
                            millisecond: 'HH:mm:ss.SSS',
                            second: 'HH:mm:ss',
                            minute: 'HH:mm',
                            hour: 'HH:mm',
                            day: 'dd/MM HH:mm'
                        }
                    }
                },
                y: {
                    min: props.options['y-min'],
                    max: props.options['y-max'],
                    title: {
                        display: true,
                        text: 'Value'
                    },
                }
            },
            plugins: {
                legend: {
                    display: true
                },
                tooltip: {
                    enabled: false
                }
            }
        }
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.variables1, initDatasets, {immediate: true});

    watch(() => props.period, initAcqui, {immediate: true});

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/

onBeforeUnmount(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    clearInterval(interval);

    interval = null;

    /*----------------------------------------------------------------------------------------------------------------*/

    chart?.destroy();

    chart = null;

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <canvas class="h-100 w-100" ref="canvasEl"></canvas>

    <!-- *********************************************************************************************************** -->

</template>
