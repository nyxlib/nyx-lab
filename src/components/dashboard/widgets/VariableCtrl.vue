<!--suppress FallThroughInSwitchStatementJS -->
<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, watch, onMounted, onBeforeUnmount} from 'vue';

import {useNyxStore} from 'vue-nyx';

import {Chart} from 'chart.js/auto';

/*--------------------------------------------------------------------------------------------------------------------*/

import 'chartjs-adapter-date-fns';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    variables1: {
        type: Array,
        required: true,
    },
    enabled: {
        type: Object,
        required: true,
    },
    period: {
        type: Number,
        required: true,
    },
    options: {
        type: Object,
        required: true,
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const canvasEl = ref(null);

let chart = null;

let interval = null;

/*--------------------------------------------------------------------------------------------------------------------*/

let stops = {};

/*--------------------------------------------------------------------------------------------------------------------*/

let datasets = {};
let lastVals = {};

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const initDatasets = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    datasets = {};
    lastVals = {};

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.data.datasets = props.variables1.map((variable) => {

        const dataset = {
            data: [/*--*/],
            label: variable,
        };

        datasets[variable] =  dataset ;
        lastVals[variable] = undefined;

        return dataset;
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/

    initWatches();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const getVal = (def) => {

    switch(def['<>'])
    {
        /*------------------------------------------------------------------------------------------------------------*/

        case 'defText':
            return /*-------------*/(def.$);

        /*------------------------------------------------------------------------------------------------------------*/

        case 'defNumber':
            return Number.parseFloat(def.$);

        /*------------------------------------------------------------------------------------------------------------*/

        case 'defLight':
            switch(def.$)
            {
                case 'Idle': return 0;
                case 'Ok': return 1;
                case 'Busy': return 2;
                case 'Alert': return 3;
            }

        /*------------------------------------------------------------------------------------------------------------*/

        case 'defSwitch':
            return def.$ === 'Off' ? 0 : 1;

        /*------------------------------------------------------------------------------------------------------------*/
    }

    return undefined;
};

/*--------------------------------------------------------------------------------------------------------------------*/

const stopWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const variable in stops)
    {
        stops[variable]();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stops = {};

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const variable of props.variables1)
    {
        const def = nyxStore.resolve(variable);

        if(def !== undefined)
        {
            stops[variable] = watch(() => def.$, () => {

                /*----------------------------------------------------------------------------------------------------*/

                const val = getVal(def);

                if(val !== undefined)
                {
                    /*------------------------------------------------------------------------------------------------*/

                    const dataset = datasets[variable];

                    if(dataset !== undefined)
                    {
                        /*--------------------------------------------------------------------------------------------*/

                        const now = Date.now();

                        /*--------------------------------------------------------------------------------------------*/

                        if(lastVals[variable] !== val)
                        {
                            lastVals[variable] = val;

                            dataset.data.push({
                                x: now,
                                y: val,
                            });

                            if(dataset.data.length === 1)
                            {
                                dataset.data.push({
                                    x: now,
                                    y: val,
                                });
                            }
                        }

                        /*--------------------------------------------------------------------------------------------*/
                    }
                }

                /*----------------------------------------------------------------------------------------------------*/

                chart.update('none');

                /*----------------------------------------------------------------------------------------------------*/
            }, {
                immediate: true
            });
        }
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initEnabled = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const dataset of chart.data.datasets)
    {
        dataset.hidden = !props.enabled[dataset.label];
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initTick = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    clearInterval(interval);

    /*----------------------------------------------------------------------------------------------------------------*/

    const timeout = props.period > 0 ? props.period : 1000;

    /*----------------------------------------------------------------------------------------------------------------*/

    interval = setInterval(() => {

        /*------------------------------------------------------------------------------------------------------------*/

        const now = Date.now();

        /*------------------------------------------------------------------------------------------------------------*/

        for(const variable of props.variables1)
        {
            /*--------------------------------------------------------------------------------------------------------*/

            const dataset = datasets[variable];

            if(dataset !== undefined && dataset.data.length > 0)
            {
                dataset.data[dataset.data.length - 1].x = now;
            }

            /*--------------------------------------------------------------------------------------------------------*/
        }

        /*------------------------------------------------------------------------------------------------------------*/

        chart.update('none');

        /*------------------------------------------------------------------------------------------------------------*/

    }, timeout);

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chart = new Chart(canvasEl.value, {
        type: 'line',
        data: {
            labels: [],
            datasets: []
        },
        options: {
            animation: false,
            responsive: true,
            maintainAspectRatio: false,
            elements: {
                line: {
                    stepped: 'after',
                    borderWidth: 1,
                },
                point: {
                    radius: 0,
                    hitRadius: 0,
                    hoverRadius: 0
                }
            },
            scales: {
                x: {
                    type: 'time',
                    time: {
                        displayFormats: {
                            millisecond: 'HH:mm:ss.SSS',
                            second: 'HH:mm:ss',
                            minute: 'HH:mm',
                            hour: 'HH:mm',
                            day: 'dd/MM HH:mm'
                        }
                    }
                },
                y: {
                    min: props.options['y-min'],
                    max: props.options['y-max'],
                    title: {
                        display: true,
                        text: 'Value'
                    },
                }
            },
            plugins: {
                legend: {
                    display: true
                },
                tooltip: {
                    enabled: false
                }
            }
        }
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.variables1, initDatasets, {immediate: true, deep: false});

    watch(() => props.enabled, initEnabled, {immediate: true, deep: true});

    watch(() => props.period, initTick, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/

onBeforeUnmount(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    clearInterval(interval);

    interval = null;

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    chart?.destroy();

    chart = null;

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <canvas class="h-100 w-100" ref="canvasEl"></canvas>

    <!-- *********************************************************************************************************** -->

</template>
