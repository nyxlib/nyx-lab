<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, watch, onMounted, onBeforeUnmount} from 'vue';

import {useNyxStore} from 'vue-nyx';

import {Chart} from 'chart.js/auto';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    variables1: {
        type: Array,
        required: true,
    },
    enabled: {
        type: Object,
        required: true,
    },
    maxPoints: {
        type: Number,
        required: true,
    },
    options: {
        type: Object,
        required: true,
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const canvasEl = ref(null);

let chart = null;

let interval = null;

/*--------------------------------------------------------------------------------------------------------------------*/

const stops = [];

/*--------------------------------------------------------------------------------------------------------------------*/

const lastVals = new Map();

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const initDatasets = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.data.datasets = [];

    lastVals.clear();

    /*----------------------------------------------------------------------------------------------------------------*/

    for(let i = 0; i < props.variables1.length; i++)
    {
        chart.data.datasets.push({
            id: props.variables1[i],
            label: props.variables1[i].split(':').pop(),
            showLine: true,
            data: [],
        });

        lastVals[i] = undefined;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/

    initWatches();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const stopWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const stop of stops)
    {
        stop();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stops.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    for(let i = 0; i < props.variables1.length; i++)
    {
        const def = nyxStore.resolve(props.variables1[i]);

        if(def !== undefined)
        {
            stops.push(watch(() => def.$, () => {

                /*----------------------------------------------------------------------------------------------------*/

                const val = nyxStore.getValue(def);

                if(val !== undefined)
                {
                    /*------------------------------------------------------------------------------------------------*/

                    const dataset = chart.data.datasets[i];

                    if(dataset !== undefined)
                    {
                        /*--------------------------------------------------------------------------------------------*/

                        const now = Date.now();

                        /*--------------------------------------------------------------------------------------------*/

                        if(lastVals[i] !== val)
                        {
                            lastVals[i] = val;

                            /*----------------------------------------------------------------------------------------*/

                            if(dataset.data.length === 0)
                            {
                                dataset.data.push({
                                    x: now,
                                    y: val,
                                });
                            }

                            dataset.data.push({
                                x: now,
                                y: val,
                            });

                            /*----------------------------------------------------------------------------------------*/

                            if(dataset.data.length > props.maxPoints)
                            {
                                dataset.data.shift();
                            }

                            /*----------------------------------------------------------------------------------------*/
                        }

                        /*--------------------------------------------------------------------------------------------*/
                    }
                }

                /*----------------------------------------------------------------------------------------------------*/

                chart.update('none');

                /*----------------------------------------------------------------------------------------------------*/
            }, {
                immediate: true
            }));
        }
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initEnabled = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const dataset of chart.data.datasets)
    {
        dataset.hidden = !props.enabled[dataset.id];
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initTick = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    clearInterval(interval);

    /*----------------------------------------------------------------------------------------------------------------*/

    interval = setInterval(() => {

        /*------------------------------------------------------------------------------------------------------------*/

        const now = Date.now();

        /*------------------------------------------------------------------------------------------------------------*/

        for(let i = 0; i < props.variables1.length; i++)
        {
            /*--------------------------------------------------------------------------------------------------------*/

            const dataset = chart.data.datasets[i];

            if(dataset && dataset.data.length > 0)
            {
                dataset.data[dataset.data.length - 1].x = now;
            }

            /*--------------------------------------------------------------------------------------------------------*/
        }

        /*------------------------------------------------------------------------------------------------------------*/

        chart.update('none');

        /*------------------------------------------------------------------------------------------------------------*/

    }, 1000);

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chart = new Chart(canvasEl.value, {
        type: 'line',
        data: {
            labels: [],
            datasets: []
        },
        options: {
            animation: false,
            responsive: true,
            maintainAspectRatio: false,
            elements: {
                line: {
                    borderWidth: 1,
                    stepped: 'after'
                },
                point: {
                    radius: 0.0,
                    hitRadius: 0.0,
                    hoverRadius: 0.0
                }
            },
            scales: {
                x: {
                    type: 'time',
                    time: {
                        displayFormats: {
                            millisecond: 'HH:mm:ss.SSS',
                            second: 'HH:mm:ss',
                            minute: 'HH:mm',
                            hour: 'HH:mm',
                            day: 'dd/MM HH:mm'
                        }
                    },
                    title: {
                        display: true,
                        text: 'Time'
                    },
                },
                y: {
                    min: props.options['y-min'],
                    max: props.options['y-max'],
                    title: {
                        display: true,
                        text: 'Value'
                    },
                }
            },
            plugins: {
                legend: {
                    display: true
                },
                tooltip: {
                    enabled: false
                }
            }
        }
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.variables1, initDatasets, {immediate: true, deep: false});

    watch(() => props.enabled, initEnabled, {immediate: true, deep: true});

    watch(() => props.period, initTick, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/

onBeforeUnmount(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    clearInterval(interval);

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    chart?.destroy();

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <canvas class="h-100 w-100" ref="canvasEl"></canvas>

    <!-- *********************************************************************************************************** -->

</template>
