<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, watch, onMounted, onBeforeUnmount} from 'vue';

import {useNyxStore} from 'vue-nyx';

import {Chart} from 'chart.js/auto';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    variables1: {
        type: Array,
        required: true,
    },
    title1: {
        type: String,
        default: null,
    },
    enabled: {
        type: Object,
        required: true,
    },
    maxPoints: {
        type: Number,
        required: true,
    },
    period: {
        type: Number,
        default: 1000,
    },
    options: {
        type: Object,
        required: true,
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const canvasEl = ref(null);

let chartInstance = null;

let interval = null;

/*--------------------------------------------------------------------------------------------------------------------*/

const stops = [];

/*--------------------------------------------------------------------------------------------------------------------*/

const lastVals = [];

/*--------------------------------------------------------------------------------------------------------------------*/

let updateScheduled = false;

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const scheduleUpdate = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(updateScheduled)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    updateScheduled = true;

    requestAnimationFrame(() => {

        updateScheduled = false;

        chartInstance.update('none');
    });

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const stopWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const stop of stops)
    {
        stop();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stops.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initDatasets = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance.data.datasets = [];

    lastVals.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/

    for(let i = 0; i < props.variables1.length; i++)
    {
        chartInstance.data.datasets.push({
            id: props.variables1[i],
            label: props.variables1[i].split(':').pop(),
            showLine: true,
            data: [],
        });

        lastVals[i] = undefined;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/

    initWatches();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(let i = 0; i < props.variables1.length; i++)
    {
        const def = nyxStore.resolve(props.variables1[i]);

        if(def !== undefined)
        {
            stops.push(watch(() => def.$, () => {

                /*----------------------------------------------------------------------------------------------------*/

                const val = nyxStore.getValue(def);

                if(val !== undefined)
                {
                    /*------------------------------------------------------------------------------------------------*/

                    const dataset = chartInstance.data.datasets[i];

                    if(dataset !== undefined)
                    {
                        /*--------------------------------------------------------------------------------------------*/

                        const now = Date.now();

                        /*--------------------------------------------------------------------------------------------*/

                        if(lastVals[i] !== val)
                        {
                            lastVals[i] = val;

                            /*----------------------------------------------------------------------------------------*/

                            if(dataset.data.length === 0)
                            {
                                dataset.data.push({
                                    x: now,
                                    y: val,
                                });
                            }

                            dataset.data.push({
                                x: now,
                                y: val,
                            });

                            /*----------------------------------------------------------------------------------------*/

                            if(dataset.data.length > props.maxPoints)
                            {
                                dataset.data.shift();
                            }

                            /*----------------------------------------------------------------------------------------*/

                            scheduleUpdate();

                            /*----------------------------------------------------------------------------------------*/
                        }

                        /*--------------------------------------------------------------------------------------------*/
                    }
                }

                /*----------------------------------------------------------------------------------------------------*/

            }, {
                immediate: true
            }));
        }
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initTitle = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance.options.scales.y.title.text = props.title1 || 'Value';

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initEnabled = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const dataset of chartInstance.data.datasets)
    {
        dataset.hidden = !props.enabled[dataset.id];
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initTick = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    clearInterval(interval);

    /*----------------------------------------------------------------------------------------------------------------*/

    interval = setInterval(() => {

        /*------------------------------------------------------------------------------------------------------------*/

        const now = Date.now();

        /*------------------------------------------------------------------------------------------------------------*/

        for(let i = 0; i < props.variables1.length; i++)
        {
            const dataset = chartInstance.data.datasets[i];

            if(dataset !== undefined && dataset.data.length > 0)
            {
                dataset.data[dataset.data.length - 1].x = now;
            }
        }

        /*------------------------------------------------------------------------------------------------------------*/

        scheduleUpdate();

        /*------------------------------------------------------------------------------------------------------------*/

    }, props.period);

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const applyOptions = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance.options.scales.y.min = props.options['y-min'];
    chartInstance.options.scales.y.max = props.options['y-max'];
    chartInstance.options.scales.y.type = props.options['y-log'] ? 'logarithmic' : 'linear';

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance = new Chart(canvasEl.value, {
        type: 'line',
        data: {
            labels: [],
            datasets: []
        },
        options: {
            animation: false,
            responsive: true,
            maintainAspectRatio: false,
            elements: {
                line: {
                    borderWidth: 1,
                    stepped: 'after'
                },
                point: {
                    radius: 0.0,
                    hitRadius: 0.0,
                    hoverRadius: 0.0
                }
            },
            scales: {
                x: {
                    type: 'time',
                    time: {
                        displayFormats: {
                            millisecond: 'HH:mm:ss.SSS',
                            second: 'HH:mm:ss',
                            minute: 'HH:mm',
                            hour: 'HH:mm',
                            day: 'dd/MM HH:mm'
                        }
                    },
                    title: {
                        display: true,
                        text: 'Time'
                    },
                },
                y: {
                    min: props.options['y-min'],
                    max: props.options['y-max'],
                    type: props.options['y-log'] ? 'logarithmic' : 'linear',
                    title: {
                        display: true,
                    },
                }
            },
            plugins: {
                legend: {
                    display: true
                },
                tooltip: {
                    enabled: false
                }
            }
        }
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.variables1, initDatasets, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.title1, initTitle, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.enabled, initEnabled, {immediate: true, deep: true});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.period, initTick, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.options, applyOptions, {immediate: false, deep: true});

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/

onBeforeUnmount(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    clearInterval(interval);

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    chartInstance?.destroy();

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <canvas class="h-100 w-100" ref="canvasEl"></canvas>

    <!-- *********************************************************************************************************** -->

</template>
