<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, watch, onMounted, onBeforeUnmount} from 'vue';

import {useNyxStore} from 'vue-nyx';

import {Chart} from 'chart.js/auto';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    variables1: {
        type: Array,
        required: true,
    },
    variables2: {
        type: Array,
        required: true,
    },
    title1: {
        type: String,
        default: null,
    },
    title2: {
        type: String,
        default: null,
    },
    enabled: {
        type: Object,
        required: true,
    },
    maxPoints: {
        type: Number,
        required: true,
    },
    options: {
        type: Object,
        required: true,
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const canvasEl = ref(null);

let chart = null;

/*--------------------------------------------------------------------------------------------------------------------*/

const stops = [];

/*--------------------------------------------------------------------------------------------------------------------*/

const lastVals1 = new Map();
const lastVals2 = new Map();

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const initDatasets = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.data.datasets = [];

    lastVals1.clear();
    lastVals2.clear();

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = Math.min(props.variables1.length, props.variables2.length);

    for(let i = 0; i < n; i++)
    {
        chart.data.datasets.push({
            id: `${props.variables1[i]} / ${props.variables2[i]}`,
            label: `${props.variables1[i].split(':').pop()} / ${props.variables2[i].split(':').pop()}`,
            showLine: false,
            data: [],
        });

        lastVals1[i] = undefined;
        lastVals2[i] = undefined;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/

    initWatches();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const stopWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const stop of stops)
    {
        stop();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    stops.length = 0;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = Math.min(props.variables1.length, props.variables2.length);

    for(let i = 0; i < n; i++)
    {
        const var1 = props.variables1[i];
        const var2 = props.variables2[i];

        /*------------------------------------------------------------------------------------------------------------*/

        const plotIfReady = () => {

            const x = lastVals2[i];
            const y = lastVals1[i];

            if(x !== undefined && y !== undefined)
            {
                const dataset = chart.data.datasets[i];

                if(dataset)
                {
                    /*------------------------------------------------------------------------------------------------*/

                    dataset.data.push({
                        x: x,
                        y: y,
                    });

                    /*------------------------------------------------------------------------------------------------*/

                    if(dataset.data.length > props.maxPoints)
                    {
                        dataset.data.shift();
                    }

                    /*------------------------------------------------------------------------------------------------*/

                    chart.update('none');

                    /*------------------------------------------------------------------------------------------------*/
                }
            }
        };

        /*------------------------------------------------------------------------------------------------------------*/

        const def1 = nyxStore.resolve(var1);

        if(def1 !== undefined)
        {
            stops.push(watch(() => def1.$, () => {

                const val = nyxStore.getValue(def1);

                if(val !== undefined)
                {
                    lastVals1[i] = val;

                    plotIfReady();
                }

            }, {immediate: true}));
        }

        /*------------------------------------------------------------------------------------------------------------*/

        const def2 = nyxStore.resolve(var2);

        if(def2 !== undefined)
        {
            stops.push(watch(() => def2.$, () => {

                const val = nyxStore.getValue(def2);

                if(val !== undefined)
                {
                    lastVals2[i] = val;

                    plotIfReady();
                }

            }, {immediate: true}));
        }

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initTitles = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.options.scales.y.title.text = props.title1 || 'Y value';

    chart.options.scales.x.title.text = props.title2 || 'X value';

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initEnabled = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const dataset of chart.data.datasets)
    {
        dataset.hidden = !props.enabled[dataset.id];
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chart = new Chart(canvasEl.value, {
        type: 'scatter',
        data: {
            datasets: []
        },
        options: {
            animation: false,
            responsive: true,
            maintainAspectRatio: false,
            elements: {
                point: {
                    radius: 1.5,
                    hitRadius: 0.0,
                    hoverRadius: 0.0
                }
            },
            scales: {
                x: {
                    min: props.options['x-min'],
                    max: props.options['x-max'],
                    title: {
                        display: true,
                    },
                },
                y: {
                    min: props.options['y-min'],
                    max: props.options['y-max'],
                    title: {
                        display: true,
                    },
                }
            },
            plugins: {
                legend: {
                    display: true
                },
                tooltip: {
                    enabled: false
                }
            }
        }
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    watch([() => props.variables1, () => props.variables2], initDatasets, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch([() => props.title1, () => props.title2], initTitles, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.enabled, initEnabled, {immediate: true, deep: true});

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/

onBeforeUnmount(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    chart?.destroy();

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <canvas class="h-100 w-100" ref="canvasEl"></canvas>

    <!-- *********************************************************************************************************** -->

</template>
