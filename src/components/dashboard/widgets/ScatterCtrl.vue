<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, watch, onMounted, onBeforeUnmount} from 'vue';

import {useNyxStore} from 'vue-nyx';

import {Chart} from 'chart.js/auto';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const nyxStore = useNyxStore();

/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    variables1: {
        type: Array,
        required: true,
    },
    variables2: {
        type: Array,
        required: true,
    },
    enabled: {
        type: Object,
        required: true,
    },
    options: {
        type: Object,
        required: true,
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const canvasEl = ref(null);

let chart = null;

/*--------------------------------------------------------------------------------------------------------------------*/

let stops = {};

/*--------------------------------------------------------------------------------------------------------------------*/

let lastVals1 = {};
let lastVals2 = {};

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const stopWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    for(const key in stops)
    {
        stops[key]();
    }

    stops = {};

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initDatasets = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    lastVals1 = {};
    lastVals2 = {};

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = Math.min(props.variables1.length, props.variables2.length);

    chart.data.datasets = [];

    for(let i = 0; i < n; i++)
    {
        chart.data.datasets.push({
            label: props.variables1[i] + ' / ' + props.variables2[i],
            showLine: false,
            data: [],
        });

        lastVals1[i] = undefined;
        lastVals2[i] = undefined;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initEnabled = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = Math.min(props.variables1.length, props.variables2.length);

    for(let i = 0; i < n; i++)
    {
        const dataset = chart.data.datasets[i];

        if(dataset)
        {
            dataset.hidden = !props.enabled[i];
        }
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    chart.update('none');

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const initWatches = () => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    const n = Math.min(props.variables1.length, props.variables2.length);

    for(let i = 0; i < n; i++)
    {
        const var1 = props.variables1[i];
        const var2 = props.variables2[i];

        /*------------------------------------------------------------------------------------------------------------*/

        const plotIfReady = () => {

            /*--------------------------------------------------------------------------------------------------------*/

            if(props.enabled[i])
            {
                const x = lastVals2[i];
                const y = lastVals1[i];

                if(x !== undefined && y !== undefined)
                {
                    const dataset = chart.data.datasets[i];

                    if(dataset)
                    {
                        dataset.data.push({
                            x: x,
                            y: y,
                        });

                        chart.update('none');
                    }
                }
            }

            /*--------------------------------------------------------------------------------------------------------*/
        };

        /*------------------------------------------------------------------------------------------------------------*/

        const def1 = nyxStore.resolve(var1);

        if(def1 !== undefined)
        {
            stops['v1:' + i] = watch(() => def1.$, () => {

                const val = nyxStore.getValue(def1);

                if(val !== undefined)
                {
                    lastVals1[i] = val;

                    plotIfReady();
                }

            }, {immediate: true});
        }

        /*------------------------------------------------------------------------------------------------------------*/

        const def2 = nyxStore.resolve(var2);

        if(def2 !== undefined)
        {
            stops['v2:' + i] = watch(() => def2.$, () => {

                const val = nyxStore.getValue(def2);

                if(val !== undefined)
                {
                    lastVals2[i] = val;

                    plotIfReady();
                }

            }, {immediate: true});
        }

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    chart = new Chart(canvasEl.value, {
        type: 'scatter',
        data: {
            datasets: []
        },
        options: {
            animation: false,
            responsive: true,
            maintainAspectRatio: false,
            scales: {
                x: {
                    title: {
                        display: true,
                        text: props.options['x-axis-label']
                    },
                },
                y: {
                    title: {
                        display: true,
                        text: props.options['y-axis-label']
                    },
                }
            },
            plugins: {
                legend: {
                    display: true
                },
                tooltip: {
                    enabled: false
                }
            }
        }
    });

    /*----------------------------------------------------------------------------------------------------------------*/

    watch([() => props.variables1, () => props.variables2], () => {

        initDatasets();

        initWatches();

        initEnabled();

    }, {immediate: true, deep: false});

    /*----------------------------------------------------------------------------------------------------------------*/

    watch(() => props.enabled, initEnabled, {immediate: true, deep: true});

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/

onBeforeUnmount(() => {

    /*----------------------------------------------------------------------------------------------------------------*/

    stopWatches();

    /*----------------------------------------------------------------------------------------------------------------*/

    chart?.destroy();

    /*----------------------------------------------------------------------------------------------------------------*/
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <canvas class="h-100 w-100" ref="canvasEl"></canvas>

    <!-- *********************************************************************************************************** -->

</template>
