<script setup>
/*--------------------------------------------------------------------------------------------------------------------*/

import {ref, onMounted, onUnmounted} from 'vue';

import {Modal} from 'bootstrap';

/*--------------------------------------------------------------------------------------------------------------------*/
/* VARIABLES                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const props = defineProps({
    lines: {
        type: Array,
        required: false,
        default: () => []
    },
});

/*--------------------------------------------------------------------------------------------------------------------*/

const modalEl = ref(null);

let modalInstance = null;

/*--------------------------------------------------------------------------------------------------------------------*/
/* FUNCTIONS                                                                                                          */
/*--------------------------------------------------------------------------------------------------------------------*/

const show = () => {

    modalInstance?.show();
};

/*--------------------------------------------------------------------------------------------------------------------*/

const hide = () => {

    modalInstance?.hide();
};

/*--------------------------------------------------------------------------------------------------------------------*/

defineExpose({
    show,
    hide,
});

/*--------------------------------------------------------------------------------------------------------------------*/
/* INITIALIZATION                                                                                                     */
/*--------------------------------------------------------------------------------------------------------------------*/

onMounted(() => {

    modalInstance = Modal.getOrCreateInstance(modalEl.value);
});

/*--------------------------------------------------------------------------------------------------------------------*/

onUnmounted(() => {

    modalInstance = /*-------------*/ null /*-------------*/;
});

/*--------------------------------------------------------------------------------------------------------------------*/
</script>

<template>

    <!-- *********************************************************************************************************** -->

    <teleport to="body">

        <!-- ******************************************************************************************************* -->

        <div class="modal" tabindex="-1" ref="modalEl">
            <div class="modal-dialog modal-dialog-centered modal-lg">
                <div class="modal-content">

                    <!-- ******************************************************************************************* -->

                    <div class="modal-header px-3 py-2">

                        <h5 class="modal-title">
                            <i class="bi bi bi-card-text"></i>
                            Addon console
                        </h5>

                        <button class="btn-close" type="button" data-bs-dismiss="modal"></button>

                    </div>

                    <!-- ******************************************************************************************* -->

                    <div class="modal-body px-3 py-2">

                        <pre class="font-monospace overflow-y-scroll" style="max-height: 80vh;"><code v-for="line in lines" :key="line">{{ `${line.trim()}\n` }}</code></pre>

                    </div>

                    <!-- ******************************************************************************************* -->

                </div>
            </div>
        </div>

        <!-- ******************************************************************************************************* -->

    </teleport>

    <!-- *********************************************************************************************************** -->

</template>
