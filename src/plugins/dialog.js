/*--------------------------------------------------------------------------------------------------------------------*/

import getRuntime from '@/runtimes.js';

/*--------------------------------------------------------------------------------------------------------------------*/
/* LOCK                                                                                                               */
/*--------------------------------------------------------------------------------------------------------------------*/

// noinspection CssUnresolvedCustomProperty
const _LOCKER_HTML = `
    <!-- *********************************************************************************************************** -->

    <div id="DEC2F4DE">
        <div class="align-self-center text-center">
            <div class="spinner-border" style="width: 4rem; height: 4rem;"></div>
            <div class="display-4">please wait…</div>
        </div>
    </div>

    <!-- *********************************************************************************************************** -->

    <style>
        /*------------------------------------------------------------------------------------------------------------*/

        #DEC2F4DE {
            /*--------------------------------------------------------------------------------------------------------*/

            display: none;
            justify-content: center;

            /*--------------------------------------------------------------------------------------------------------*/

            position: fixed;

            top: 0;
            bottom: 0;

            left: 0;
            right: 0;

            /*--------------------------------------------------------------------------------------------------------*/

            z-index: 9999;

            /*--------------------------------------------------------------------------------------------------------*/

            background-color: var(--bs-body-bg);

            /*--------------------------------------------------------------------------------------------------------*/
        }

        /*------------------------------------------------------------------------------------------------------------*/

        body[data-environment="desktop"][data-maximized="false"] > #DEC2F4DE {

            top: 48px !important;
            bottom: 01px !important;

            left: 01px !important;
            right: 01px !important;
        }

        /*------------------------------------------------------------------------------------------------------------*/
    </style>

    <!-- *********************************************************************************************************** -->
`;

/*--------------------------------------------------------------------------------------------------------------------*/

let _curLockCnt = 0;

/*--------------------------------------------------------------------------------------------------------------------*/
/* LOCKER                                                                                                             */
/*--------------------------------------------------------------------------------------------------------------------*/

const _lock = () => {

    if(_curLockCnt <= 0)
    {
        document.getElementById('DEC2F4DE').style.display = 'flex';

        _curLockCnt = 1;
    }
    else
    {
        _curLockCnt++;
    }
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _unlock = () => {

    if(_curLockCnt <= 1)
    {
        document.getElementById('DEC2F4DE').style.display = 'none';

        _curLockCnt = 0;
    }
    else
    {
        _curLockCnt--;
    }
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* DIALOGS                                                                                                            */
/*--------------------------------------------------------------------------------------------------------------------*/

const _notify_step2 = (title, body) => {

    return getRuntime().notifySend(title, body);
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _notify = (message, title) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(!message)
    {
        return;
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    if(typeof message !== 'string')
    {
        message = String(message);
    }

    if(typeof title !== 'string')
    {
        title = String(title);
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    console.log(`title: ${title}, body: ${message}`);

    /*----------------------------------------------------------------------------------------------------------------*/

    const runtime = getRuntime();

    /*----------------------------------------------------------------------------------------------------------------*/

    return runtime.notifyIsPermissionGranted().then((granted) => {

        if(!granted)
        {
            return runtime.notifyRequestPermission().then((permission) => {

                if(permission === 'granted')
                {
                    return _notify_step2(title, message);
                }
            });
        }
        else
        {
            return _notify_step2(title, message);
        }
    });

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _success = (message) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const el = document.querySelector('[data-tauri-drag-region]')?.closest('.navbar');

    /*----------------------------------------------------------------------------------------------------------------*/

    if(el)
    {
        el.classList.remove('nyx-bg1');
        el.classList.add('bg-success');

        setTimeout(() => {

            el.classList.remove('bg-success');
            el.classList.add('nyx-bg1');

        }, 500);
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    _notify(message, 'Success');
    _unlock();

    /*----------------------------------------------------------------------------------------------------------------*/

    return Promise.resolve();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _warning = (message) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const el = document.querySelector('[data-tauri-drag-region]')?.closest('.navbar');

    /*----------------------------------------------------------------------------------------------------------------*/

    if(el)
    {
        el.classList.remove('nyx-bg1');
        el.classList.add('bg-warning');

        setTimeout(() => {

            el.classList.remove('bg-warning');
            el.classList.add('nyx-bg1');

        }, 500);
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    _notify(message, 'Warning');
    _unlock();

    /*----------------------------------------------------------------------------------------------------------------*/

    return Promise.resolve();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _error = (message) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    const el = document.querySelector('[data-tauri-drag-region]')?.closest('.navbar');

    /*----------------------------------------------------------------------------------------------------------------*/

    if(el)
    {
        el.classList.remove('nyx-bg1');
        el.classList.add('bg-danger');

        setTimeout(() => {

            el.classList.remove('bg-danger');
            el.classList.add('nyx-bg1');

        }, 500);
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    _notify(message, 'Error');
    _unlock();

    /*----------------------------------------------------------------------------------------------------------------*/

    return Promise.resolve();

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _show = (message, title, type = null) => {

    /*----------------------------------------------------------------------------------------------------------------*/

    if(typeof message !== 'string')
    {
        message = String(message);
    }

    if(typeof title !== 'string')
    {
        title = String(title);
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    return getRuntime().message(message, {
        title: title || '',
        kind: type || 'info',
    }).catch((e) => {

        console.log(e);
    });

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _confirm = (message, title, type = null) => {

    return getRuntime().confirm(message, {
        title: title,
        kind: type || 'info'
    });
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _open = (defaultPath, typeMime, typeName, typeExts) => {

    return getRuntime().open(defaultPath, typeMime, typeName, typeExts);
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _save = (defaultPath, typeMime, typeName, typeExts, contents) => {

    return getRuntime().save(defaultPath, typeMime, typeName, typeExts, contents);
};

/*--------------------------------------------------------------------------------------------------------------------*/

export default {

    install(app)
    {
        /*------------------------------------------------------------------------------------------------------------*/

        document.body.insertAdjacentHTML('beforeend', _LOCKER_HTML);

        /*------------------------------------------------------------------------------------------------------------*/

        app.provide('dialog', {
            /* LOCKER */
            lock: _lock,
            unlock: _unlock,
            /* DIALOGS */
            notify: _notify,
            /**/
            success: _success,
            warning: _warning,
            error: _error,
            /**/
            show: _show,
            /**/
            confirm: _confirm,
            /**/
            open: _open,
            save: _save,
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }
};

