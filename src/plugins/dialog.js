/*--------------------------------------------------------------------------------------------------------------------*/

import * as notification from '@tauri-apps/plugin-notification';

import * as dialog from '@tauri-apps/plugin-dialog';

import * as fs from '@tauri-apps/plugin-fs';

/*--------------------------------------------------------------------------------------------------------------------*/

const HAS_TAURI = window['__TAURI__'] !== undefined;

/*--------------------------------------------------------------------------------------------------------------------*/

const Notification_isPermissionGranted = () => Promise.resolve(Notification.permission === 'granted');

/*--------------------------------------------------------------------------------------------------------------------*/
/* LOCK                                                                                                               */
/*--------------------------------------------------------------------------------------------------------------------*/

// noinspection CssUnresolvedCustomProperty
const _LOCKER_HTML = `
    <!-- *********************************************************************************************************** -->

    <div id="DEC2F4DE">
        <div class="align-self-center text-center">
            <div class="spinner-border" style="width: 4rem; height: 4rem;"></div>
            <div class="display-4">please wait…</div>
        </div>
    </div>

    <!-- *********************************************************************************************************** -->

    <style>
        /*------------------------------------------------------------------------------------------------------------*/

        #DEC2F4DE {
            /*--------------------------------------------------------------------------------------------------------*/

            display: none;
            justify-content: center;

            /*--------------------------------------------------------------------------------------------------------*/

            position: fixed;

            top: 0;
            bottom: 0;

            left: 0;
            right: 0;

            /*--------------------------------------------------------------------------------------------------------*/

            z-index: 9999;

            /*--------------------------------------------------------------------------------------------------------*/

            background-color: var(--bs-body-bg);

            /*--------------------------------------------------------------------------------------------------------*/
        }

        /*------------------------------------------------------------------------------------------------------------*/

        body[data-environment="tauri"][data-maximized="false"] > #DEC2F4DE {

            top: 48px !important;
            bottom: 01px !important;

            left: 01px !important;
            right: 01px !important;
        }

        /*------------------------------------------------------------------------------------------------------------*/
    </style>

    <!-- *********************************************************************************************************** -->
`;

/*--------------------------------------------------------------------------------------------------------------------*/

let _curLockCnt = 0;

/*--------------------------------------------------------------------------------------------------------------------*/

const _lock = () => {

    if(_curLockCnt <= 0)
    {
        document.getElementById('DEC2F4DE').style.display = 'flex';

        _curLockCnt = 1;
    }
    else
    {
        _curLockCnt++;
    }
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _unlock = () => {

    if(_curLockCnt <= 1)
    {
        document.getElementById('DEC2F4DE').style.display = 'none';

        _curLockCnt = 0;
    }
    else
    {
        _curLockCnt--;
    }
};

/*--------------------------------------------------------------------------------------------------------------------*/
/* DIALOGS                                                                                                            */
/*--------------------------------------------------------------------------------------------------------------------*/

const _notify_step2 = (title, body) => {

    if(HAS_TAURI)
    {
        notification.sendNotification({
            title: title,
            body: body,
        });
    }
    else
    {
        new Notification(title, {
            body: body
        });
    }
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _notify = (message, title) => {

    if(!message)
    {
        return;
    }

    if(typeof message !== 'string')
    {
        message = String(message);
    }

    if(typeof title !== 'string')
    {
        title = String(title);
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    console.log(`title: ${title}, body: ${message}`);

    /*----------------------------------------------------------------------------------------------------------------*/

    if(HAS_TAURI)
    {
        /*------------------------------------------------------------------------------------------------------------*/

        notification.isPermissionGranted().then((granted) => {

            if(!granted)
            {
                notification.requestPermission().then((permission) => {

                    if(permission === 'granted')
                    {
                        _notify_step2(title, message);
                    }
                });
            }
            else
            {
                _notify_step2(title, message);
            }
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }
    else if('Notification' in /* NOSONAR */ window)
    {
        /*------------------------------------------------------------------------------------------------------------*/

        Notification_isPermissionGranted().then((granted) => {

            if(!granted)
            {
                Notification.requestPermission().then((permission) => {

                    if(permission === 'granted')
                    {
                        _notify_step2(title, message);
                    }
                });
            }
            else
            {
                _notify_step2(title, message);
            }
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _success = (message) => {

    const el = document.querySelector('[data-tauri-drag-region]')?.closest('.navbar');

    if(el)
    {
        el.classList.remove('nyx-bg1');
        el.classList.add('bg-success');

        setTimeout(() => {

            el.classList.remove('bg-success');
            el.classList.add('nyx-bg1');

        }, 500);
    }

    _notify(message, 'Success');
    _unlock();

    return Promise.resolve();
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _warning = (message) => {

    const el = document.querySelector('[data-tauri-drag-region]')?.closest('.navbar');

    if(el)
    {
        el.classList.remove('nyx-bg1');
        el.classList.add('bg-warning');

        setTimeout(() => {

            el.classList.remove('bg-warning');
            el.classList.add('nyx-bg1');

        }, 500);
    }

    _notify(message, 'Warning');
    _unlock();

    return Promise.resolve();
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _error = (message) => {

    const el = document.querySelector('[data-tauri-drag-region]')?.closest('.navbar');

    if(el)
    {
        el.classList.remove('nyx-bg1');
        el.classList.add('bg-danger');

        setTimeout(() => {

            el.classList.remove('bg-danger');
            el.classList.add('nyx-bg1');

        }, 500);
    }

    _notify(message, 'Error');
    _unlock();

    return Promise.resolve();
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _show = (message, title, type = null) => {

    if(typeof message !== 'string')
    {
        message = String(message);
    }

    if(typeof title !== 'string')
    {
        title = String(title);
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    if(HAS_TAURI)
    {
        /*------------------------------------------------------------------------------------------------------------*/

        dialog.message(message, {title: title, kind: type || 'error'}).catch((e) => {

            console.log(e);
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }
    else
    {
        /*------------------------------------------------------------------------------------------------------------*/

        alert(message);

        /*------------------------------------------------------------------------------------------------------------*/
    }

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _confirm = (message, title, type = null) => {

    if(HAS_TAURI)
    {
        /*------------------------------------------------------------------------------------------------------------*/

        return dialog.confirm(message, {title: title, kind: type || 'info'});

        /*------------------------------------------------------------------------------------------------------------*/
    }
    else
    {
        /*------------------------------------------------------------------------------------------------------------*/

        return Promise.resolve(confirm(message));

        /*------------------------------------------------------------------------------------------------------------*/
    }
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _open = (defaultPath, typeMime, typeName, typeExts) => {

    if(HAS_TAURI)
    {
        /*------------------------------------------------------------------------------------------------------------*/

        return dialog.open({
            multiple: false,
            defaultPath: defaultPath,
            filters: [{
                name: typeName,
                extensions: typeExts,
            }]
        }).then((filename) => {

            if(filename)
            {
                return fs.readTextFile(filename).then((text) => {

                    return [text, filename];
                });
            }
            else
            {
                throw new Error('Operation cancelled');
            }
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }
    else
    {
        /*------------------------------------------------------------------------------------------------------------*/

        return new Promise((resolve, reject) => {

            /*--------------------------------------------------------------------------------------------------------*/

            const el = document.createElement('input');

            el.accept = typeExts.map((x) => `.${x}`).join(',');

            el.type = 'file';

            /*--------------------------------------------------------------------------------------------------------*/

            el.addEventListener('change', () => {

                /*----------------------------------------------------------------------------------------------------*/

                const file = el.files?.[0];

                if(file)
                {
                    file.text().then((text) => {

                        resolve([text, null]);

                    }, reject);
                }
                else
                {
                    reject(new Error('Operation cancelled'));
                }

                /*----------------------------------------------------------------------------------------------------*/

                el.remove();

                /*----------------------------------------------------------------------------------------------------*/

            }, {
                once: true
            });

            /*--------------------------------------------------------------------------------------------------------*/

            document.body.appendChild(el);

            /*--------------------------------------------------------------------------------------------------------*/

            el.click();

            /*--------------------------------------------------------------------------------------------------------*/
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }
};

/*--------------------------------------------------------------------------------------------------------------------*/

const _save = (defaultPath, typeMime, typeName, typeExts, contents) => {

    if(HAS_TAURI)
    {
        /*------------------------------------------------------------------------------------------------------------*/

        return dialog.save({
            defaultPath: defaultPath,
            filters: [
                {
                    name: typeName,
                    extensions: typeExts,
                },
            ],
        }).then((filename) => {

            if(filename)
            {
                return fs.writeTextFile(filename, contents).then(() => {

                    return filename;
                });
            }
            else
            {
                throw new Error('Operation cancelled');
            }
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }
    else
    {
        /*------------------------------------------------------------------------------------------------------------*/

        const blob = new Blob([contents], {type: typeMime});

        const el = document.createElement('a');

        el.href = URL.createObjectURL(blob);
        el.download = defaultPath;
        el.style.display = 'none';

        document.body.appendChild(el);  /* NOSONAR */
        el.click();
        document.body.removeChild(el);  /* NOSONAR */

        /*------------------------------------------------------------------------------------------------------------*/

        return Promise.resolve(null);

        /*------------------------------------------------------------------------------------------------------------*/
    }
};

/*--------------------------------------------------------------------------------------------------------------------*/

export default {

    install(app)
    {
        /*------------------------------------------------------------------------------------------------------------*/

        document.body.insertAdjacentHTML('beforeend', _LOCKER_HTML);

        /*------------------------------------------------------------------------------------------------------------*/

        app.provide('dialog', {
            /* LOCKER */
            lock: _lock,
            unlock: _unlock,
            /* DIALOGS */
            notify: _notify,
            /**/
            success: _success,
            warning: _warning,
            error: _error,
            /**/
            show: _show,
            /**/
            confirm: _confirm,
            /**/
            open: _open,
            save: _save,
        });

        /*------------------------------------------------------------------------------------------------------------*/
    }
};

